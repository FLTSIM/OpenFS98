#!/usr/bin/env python3
"""Generate relocation-aware normal model data and build eight MDL DLLs.

Only data, the Sopwith literal, and resources are extracted. Every relocated
code pointer must name a known C/ABI entry; unknown targets stop generation.
Generated artifacts and retail payloads remain under ignored bin/mdl-diff/.
"""
import argparse
import json
from pathlib import Path
import struct
import subprocess

from dialogmap import Fs98Pe
from gen_gauges import relocations
from mdl_survey import survey

NAMES = ('BOEING737-400_N', 'BELL_206B_JETRANGER_N', 'CESSNA182RRG_N',
         'CESSNA182S_N', 'EXTRA300S_N', 'LEAR45_N', 'SCHWEIZER2_32_N', 'SOPWITHCAMEL_N')


def generate(path, directory, kind, code_override=None):
    pe = Fs98Pe(path)
    record = survey(path)
    data = record['sections']['.data']
    start, size = data['rva'], data['size']
    exports = pe.exports()
    active_end = exports['Linkage'] + 0x24
    if not start < active_end <= start + size:
        raise ValueError(f'{path}: invalid model data bounds')
    code = dict(code_override) if code_override is not None else {int(record['update_rva'], 16): '_mdl_update@4'}
    for slot, symbol in ([] if code_override is not None else [('0x4', '_mdl_nop'), ('0x8', '_mdl_nop'),
                         ('0x18', '_mdl_attach@4'), ('0x1c', '_mdl_state@4'),
                         ('0x20', '_mdl_detach')]):
        target = int(record['linkage'][slot], 16)
        if target in code and code[target] != symbol:
            raise ValueError(f'{path}: overlapping code entries')
        code[target] = symbol
    payload = pe.read_bytes(pe.file_offset(start, size), size)
    directory.mkdir(parents=True, exist_ok=True)
    payload_path = directory / 'model.data.bin'
    payload_path.write_bytes(payload)
    lines = ['/* Generated by tools/build_mdls.py. No extracted instructions. */',
             '.section .mdlimg,"dw"' if code_override is not None else '.data',
             '.balign 16', '.globl _mdl_image', '_mdl_image:']
    if kind == 7:
        literal = pe.read_bytes(pe.file_offset(0x1037, 14), 14)
        if literal != b'Sopwith Camel\0':
            raise ValueError(f'{path}: Sopwith literal moved')
        lines += ['.zero 0x1037', '.byte ' + ','.join(str(v) for v in literal),
                  f'.zero {start - 0x1037 - len(literal)}']
    else:
        lines += [f'.zero {start}']
    cursor = start
    model_relocs = []
    for address, target in sorted(relocations(pe)):
        if not start <= address < start + size:
            continue
        if address < cursor or address + 4 > active_end:
            raise ValueError(f'{path}: overlapping or CRT-tail relocation')
        if address > cursor:
            lines += [f'.incbin {json.dumps(str(payload_path.resolve()))}, {cursor - start}, {address - cursor}']
        if target in code:
            expression = code[target]
        elif start <= target < active_end:
            expression = f'_mdl_image + 0x{target:x}'
        else:
            raise ValueError(f'{path}: unrecognized relocated target 0x{target:x}')
        lines += [f'.long {expression}']
        model_relocs.append([address, target])
        cursor = address + 4
    lines += [f'.incbin {json.dumps(str(payload_path.resolve()))}, {cursor - start}, {start + size - cursor}']
    for symbol, rva in [('ImportTable', exports['ImportTable']), ('Linkage', exports['Linkage']),
                        ('mdl_header', int(record['header_rva'], 16))]:
        lines += [f'.globl _{symbol}', f'.set _{symbol}, _mdl_image + 0x{rva:x}']
    (directory / 'model_data.S').write_text('\n'.join(lines) + '\n')
    (directory / 'model_config.h').write_text(f'/* Generated from {path.name}. */\n#define MDL_KIND {kind}\n')
    (directory / 'model.def').write_text('EXPORTS\n    ImportTable DATA\n    Linkage DATA\n')

    resources = bytearray(struct.pack('<IIHHHHIHHII', 0, 32, 0xffff, 0, 0xffff, 0, 0, 0, 0, 0, 0))
    resource_meta = []
    for resource in pe.resources():
        if not all(isinstance(resource[key], int) and 0 <= resource[key] <= 65535
                   for key in ('type', 'id', 'language')):
            raise ValueError(f'{path}: unsupported named resource')
        resources += struct.pack('<IIHHHHIHHII', resource['size'], 32, 0xffff,
                                 resource['type'], 0xffff, resource['id'], 0,
                                 0x1030, resource['language'], 0, 0)
        resources += pe.read_bytes(pe.file_offset(resource['rva'], resource['size']), resource['size'])
        resources += bytes(-len(resources) % 4)
        resource_meta.append({key: resource[key] for key in ('type', 'id', 'language', 'size')})
    (directory / 'model.res').write_bytes(resources)
    record.update(kind=kind, installed=str(path.relative_to('orig')),
                  rebuilt=str((directory.parent / 'models' / path.name).resolve()),
                  model_relocs=model_relocs, active_end=active_end,
                  resources=resource_meta, linkage_rva=exports['Linkage'])
    return record


def build(record, directory, module_source='src/mdl/mdl_module.c', update_source='src/mdl/mdl_normal.c'):
    output = Path(record['rebuilt'])
    output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['i686-w64-mingw32-windres', '-J', 'res', '-O', 'coff',
                    str(directory / 'model.res'), str(directory / 'resource.o')], check=True)
    command = ['i686-w64-mingw32-gcc', '-std=c99', '-Os', '-Wall', '-Wextra',
               '-ffreestanding', '-fno-builtin', '-fno-asynchronous-unwind-tables',
               '-Iinclude', '-Isrc/mdl', '-I' + str(directory), '-shared', '-nostdlib',
               '-Wl,--entry=_DllMain@12', '-Wl,--disable-dynamicbase', '-Wl,--disable-nxcompat',
               '-Wl,--image-base=' + record['image_base'], '-o', str(output),
               str(update_source), str(module_source), str(directory / 'model_data.S'),
               str(directory / 'model.def'), str(directory / 'resource.o'), '-lkernel32']
    result = subprocess.run(command, text=True, capture_output=True)
    (directory / 'build.log').write_text(result.stdout + result.stderr)
    if result.returncode or result.stderr:
        raise RuntimeError(f'{output.name}: compiler output\n{result.stdout}{result.stderr}')
    print(f'{output.name}: built, {len(record["model_relocs"])} data relocations', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path('bin/mdl-diff'))
    args = parser.parse_args()
    paths = sorted(path for path in Path('orig/Aircraft').rglob('*')
                   if path.is_file() and path.name.upper().endswith('_N.MDL'))
    if tuple(path.stem for path in paths) != NAMES:
        raise ValueError('expected the eight reference normal MDLs in known kind order')
    records = []
    for kind, path in enumerate(paths):
        directory = args.output / path.stem
        record = generate(path, directory, kind)
        build(record, directory)
        records.append(record)
    (args.output / 'modules.json').write_text(json.dumps(records, indent=2) + '\n')
    lines = ['/* Generated MDL boundaries and relocation/resource metadata. */']
    for index, record in enumerate(records):
        lines += [f'static const struct model_reloc relocs_{index}[] = {{']
        lines += [f'    {{0x{address:x}, 0x{target:x}}},'
                  for address, target in record['model_relocs']]
        lines += ['};', f'static const struct model_resource resources_{index}[] = {{']
        lines += ['    {%d, %d, %d, %d},' % tuple(resource[key] for key in ('type', 'id', 'language', 'size'))
                  for resource in record['resources']]
        lines += ['};']
    lines += ['static const struct model_spec models[] = {']
    for index, record in enumerate(records):
        data = record['sections']['.data']
        values = [index, data['rva'], data['size'],
                  Fs98Pe(Path(record['path'])).exports()['ImportTable'], record['linkage_rva'],
                  int(record['header_rva'], 16), record['active_end']]
        lines += ['    {' + json.dumps(str(Path(record['path']).resolve())) + ', '
                  + json.dumps(record['rebuilt']) + ', ' + ', '.join(hex(value) for value in values)
                  + f', relocs_{index}, {len(record["model_relocs"])}, resources_{index}, {len(record["resources"])}' + '},']
    lines += ['};']
    (args.output / 'modules.inc').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
