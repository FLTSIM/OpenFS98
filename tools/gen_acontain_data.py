#!/usr/bin/env python3
"""Extract ACONTAIN.DLL's .data image and colour table into C.

ACONTAIN keeps its ImportTable, Linkage, a table of aircraft.cfg keys, its
strings and its two string pools in one .data section.  The reimplementation
keeps one image laid out the same way, so offsets in a listing can be grepped
for in the C directly and the difftest can compare the images.

Two outputs:

  acontain_data.inc     .data from +0x78 (after ImportTable and Linkage, which
                        the C defines itself) to the end of the section.  No
                        pointers: the pools at +0x39c/+0x3a0 start null.
  acontain_colours.inc  the .rdata table of colour names and ids at
                        0x20603000, its name pointers turned into offsets
                        into the image.

Usage: tools/gen_acontain_data.py [orig/Modules/ACONTAIN.DLL] [src/acontain]
"""
import os, struct, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'orig/Modules/ACONTAIN.DLL'
DST = sys.argv[2] if len(sys.argv) > 2 else 'src/acontain'

DATA_VA, RDATA_VA = 0x20604000, 0x20603000
COLOURS_END = 0x206031a8        # the lookup's loop bound, at .text+0x13d4

b = open(SRC, 'rb').read()
e = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, e + 6)[0]
base = struct.unpack_from('<I', b, e + 24 + 28)[0]
so = e + 24 + struct.unpack_from('<H', b, e + 20)[0]
secs = {}
for _ in range(nsec):
    name = b[so:so + 8].rstrip(b'\0').decode()
    vsz, va, rsz, ro = struct.unpack_from('<IIII', b, so + 8)
    secs[name] = (va, vsz, rsz, ro)
    so += 40

va, vsz, rsz, ro = secs['.data']
assert base + va == DATA_VA, 'ACONTAIN .data is not at 0x20604000'
assert vsz == 0x3b0 and rsz >= vsz, '.data size changed'
data = b[ro:ro + vsz]
u32 = lambda o: struct.unpack_from('<I', data, o)[0]
s32 = lambda o: struct.unpack_from('<i', data, o)[0]
cstr = lambda o: data[o:data.index(b'\0', o)].decode('latin1')

# ImportTable: host, GLOBAL, CHAIN, G3D, PANELS, UTIL, terminator.
assert [u32(8 * i) for i in range(7)] == [1, 2, 4, 14, 15, 20, 0], 'ImportTable'

# Linkage, as acontain.c's struct describes it.
LINKAGE = [23, 0x20601020, 0x20601040, 0, 0, 0,
           0x206022b0, 0x20601fa0, 0x20601060, 0x20601920, 0x20601970,
           0x20601bf0, 0x20601c50, 0x20601cd0, 0x20601f00, 0x20601f80]
assert [u32(0x38 + 4 * i) for i in range(16)] == LINKAGE, 'Linkage'

# The key table at +0x78: twelve { string id, type, alias string id }.
KEYS = [(0x2310, 0x24, 0), (0x231e, 0, 0), (0x2313, 0x0f, 0),
        (0x2317, -2, 0x231c), (0x2317, 0x24, 0x231c),
        (0x2316, -2, 0x231b), (0x2316, 0x24, 0x231b),
        (0x2315, -2, 0x231a), (0x2315, 0x24, 0x231a),
        (0x2314, -2, 0x2319), (0x2314, 0x24, 0x2319),
        (0x2318, 0x24, 0)]
assert [(u32(0x78 + 12 * k), s32(0x7c + 12 * k), u32(0x80 + 12 * k))
        for k in range(12)] == KEYS, 'key table'

STRINGS = {0x108: '.', 0x10c: '%s.%d', 0x114: 'AIRtoCONTAINER', 0x124: 'models',
           0x12c: 'NORMAL', 0x134: 'CRASH', 0x38c: 'colors', 0x394: '%.2d',
           0x3a4: ''}
for off, text in STRINGS.items():
    assert cstr(off) == text, 'string at +%#x' % off
assert data[0x39c:0x3b0] == bytes(0x14), 'pools and padding are not zero'

# The colour table: { name pointer into .data, id }.
rva, rvsz, rrsz, rro = secs['.rdata']
assert base + rva == RDATA_VA, '.rdata is not at 0x20603000'
rdata = b[rro:rro + rvsz]
colours = []
for o in range(0, COLOURS_END - RDATA_VA, 8):
    ptr, cid = struct.unpack_from('<II', rdata, o)
    assert DATA_VA + 0x13c <= ptr < DATA_VA + 0x38c, 'colour name outside .data'
    assert 0xf000 <= cid <= 0xf034, 'colour id'
    colours.append((ptr - DATA_VA, cid, cstr(ptr - DATA_VA)))
assert len(colours) == 53, 'colour count'
assert struct.unpack_from('<II', rdata, COLOURS_END - RDATA_VA) == (0, 0), 'table end'

body = data[0x78:]
with open(os.path.join(DST, 'acontain_data.inc'), 'w') as f:
    f.write('/* Generated by tools/gen_acontain_data.py from %s -- do not edit.\n' % SRC)
    f.write(' *\n'
            ' * ACONTAIN\'s .data from +0x78 to +0x%x as the file holds it: the\n'
            ' * aircraft.cfg key table at +0x78, the strings from +0x108, and the\n'
            ' * two string pools at +0x39c and +0x3a0 (null).\n'
            ' */\n' % len(data))
    for i in range(0, len(body), 16):
        f.write('    ' + ' '.join('0x%02x,' % c for c in body[i:i + 16]) + '\n')

with open(os.path.join(DST, 'acontain_colours.inc'), 'w') as f:
    f.write('/* Generated by tools/gen_acontain_data.py from %s -- do not edit.\n' % SRC)
    f.write(' *\n'
            ' * The colour table at .rdata 0x20603000, in its own order (which is\n'
            ' * alphabetical: the lookup stops early on it).  Each name is an\n'
            ' * offset into the .data image.\n'
            ' */\n')
    for off, cid, name in colours:
        f.write('    { 0x%03x, 0x%04x },   /* %s */\n' % (off, cid, name))
