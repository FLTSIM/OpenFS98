#!/usr/bin/env python3
"""Extract ADVDRV.DLL's .data image and .rdata constants into C.

ADVDRV keeps ImportTable at +0, Linkage at +0x48, then its tables and all of
its state in one 0x32a0-byte .data section (0x1400 bytes on disk, the rest
zero).  The reimplementation keeps that layout so the harness can compare the
whole image.  Its 372 relocations are code pointers -- the Linkage, the
opcode table at +0xd8, the operator pairs at +0x198, the 176 variable
descriptors at +0x318, the weather table at +0x10f8 and the skip table at
+0x1230 -- and six pointers into .data.  All are zeroed in the image and
listed separately, with the address each held, for advdrv.c to install.

The floating-point constants in .rdata are copied out as bytes too, so that
the code reads retail's exact values rather than retyped decimals.

Usage: tools/gen_advdrv_data.py [orig/Modules/ADVDRV.DLL]
                                [src/advdrv/advdrv_data.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/ADVDRV.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/advdrv/advdrv_data.inc"

BASE = 0x20610000
TEXT_VA = 0x20611000
TEXT_END = 0x20619000
RDATA_VA = 0x20619000
RDATA_CONSTANTS = 0x300            # the constant pool ends where exports begin
DATA_VA = 0x2061A000
SIZE = 0x32A0
IMPORTS = 0x000
LINKAGE = 0x048

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * i) for i in range(9)] == [
    1, 2, 4, 7, 3, 39, 20, 22, 0
], "ImportTable"
assert all(u32(IMPORTS + 8 * i + 4) == 0 for i in range(9)), "import links"
assert u32(LINKAGE) == 21, "module id"
assert [u32(LINKAGE + offset) for offset in (0x0C, 0x10, 0x14)] == [0, 0, 0], \
    "Linkage header"
assert data[0x80:0x8D] == b"fs98\\adv\\wav\0", "wave directory"
assert data[0xA8:0xC8] == b"FS6 Adventure\x1a\0\0FS6X Adventure\x1a\0", \
    "file magic"
assert data[0x190:0x197] == b"%0*.*f\0", "number format"
assert data[0x12E0:0x12F0] == b"CACHE_WAV_FILES\0", "cache key"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size
relocations.sort()
assert len(relocations) == 372, "relocation count changed"

entries = []
for offset in relocations:
    value = u32(offset)
    if TEXT_VA <= value < TEXT_END:
        entries.append((offset, value, "code"))
    else:
        assert DATA_VA <= value < DATA_VA + SIZE, "relocation points outside"
        entries.append((offset, value - DATA_VA, "data"))
    data[offset:offset + 4] = bytes(4)
assert [e[0] for e in entries if e[2] == "data"] == \
    [0x0D0, 0x410, 0xFDC, 0xFF0, 0x1004, 0x10CC], "data pointers"

rd_rva, rd_size, _, rd_raw = sections[".rdata"]
assert BASE + rd_rva == RDATA_VA, ".rdata moved"
rdata = blob[rd_raw:rd_raw + RDATA_CONSTANTS]
assert struct.unpack_from("<d", rdata, 0x18)[0] == 0.3048, "constant pool"

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_advdrv_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * ADVDRV's complete 0x32a0-byte .data image with its relocated\n")
    output.write(" * pointers zeroed, the list of those pointers, and the .rdata\n")
    output.write(" * constant pool.\n */\n")
    output.write("#ifdef ADVDRV_IMAGE\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))
    output.write("#endif\n#ifdef ADVDRV_RELOCS\n")
    for offset, value, kind in entries:
        if kind == "code":
            output.write("    ADVDRV_CODE(0x%04x, 0x%08x)\n" % (offset, value))
        else:
            output.write("    ADVDRV_DATA(0x%04x, 0x%04x)\n" % (offset, value))
    output.write("#endif\n#ifdef ADVDRV_RDATA\n")
    for offset in range(0, RDATA_CONSTANTS, 16):
        chunk = rdata[offset:offset + 16]
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    %s\n" % values)
    output.write("#endif\n")

print("wrote", DST)
