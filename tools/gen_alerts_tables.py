#!/usr/bin/env python3
"""Extract Alerts' button string ids from its two-level retail jump table."""
from pathlib import Path
import sys

from dialogmap import Fs98Pe, SurveyError


def main():
    pe = Fs98Pe(sys.argv[1] if len(sys.argv) > 1 else 'orig/English/Alerts.DLL')
    values = []
    for bit in range(8):
        index = pe.byData[pe.file_offset(0x192c + (1 << bit) - 1)]
        target = pe.va_uint32(pe.uiBase + 0x1908 + index * 4)
        offset = pe.file_offset(target - pe.uiBase, 18)
        if pe.read_bytes(offset + 13, 1) != b'\x68':
            raise SurveyError('button-label instruction layout moved')
        values.append(pe.read_uint32(offset + 14))
    text_buffer = '/* Generated by tools/gen_alerts_tables.py from retail Alerts; do not edit. */\n'
    text_buffer += 'static const uint32_t s_button_text[8] = {\n    '
    text_buffer += ', '.join(f'0x{value:x}' for value in values) + '\n};\n'
    Path('src/alerts/alerts_tables.inc').write_text(text_buffer)


if __name__ == '__main__':
    main()
