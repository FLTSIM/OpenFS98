#!/usr/bin/env python3
"""Extract Alerts' button string ids from its two-level retail jump table."""
from pathlib import Path
import sys

from dialogmap import Fs98Pe, SurveyError


def main():
    pPe = Fs98Pe(sys.argv[1] if len(sys.argv) > 1 else 'orig/English/Alerts.DLL')
    aValues = []
    for iBit in range(8):
        uiIndex = pPe.byData[pPe.file_offset(0x192c + (1 << iBit) - 1)]
        uiTarget = pPe.va_uint32(pPe.uiBase + 0x1908 + uiIndex * 4)
        iOffset = pPe.file_offset(uiTarget - pPe.uiBase, 18)
        if pPe.read_bytes(iOffset + 13, 1) != b'\x68':
            raise SurveyError('button-label instruction layout moved')
        aValues.append(pPe.read_uint32(iOffset + 14))
    szText = '/* Generated by tools/gen_alerts_tables.py from retail Alerts; do not edit. */\n'
    szText += 'static const uint32 s_auiButtonText[8] = {\n    '
    szText += ', '.join(f'0x{uiValue:x}' for uiValue in aValues) + '\n};\n'
    Path('src/alerts/alerts_tables.inc').write_text(szText)


if __name__ == '__main__':
    main()
