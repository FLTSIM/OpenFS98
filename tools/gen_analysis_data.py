#!/usr/bin/env python3
"""Extract ANALYSIS.DLL's .data image and its .rdata constants into C.

ANALYSIS keeps one 0x32c-byte .data section: its state, the countdown and
the two overlapping tables at +0x70, ImportTable at +0x88, Linkage at +0xc8,
the dialogs' strings and blocks, the options' exchange table at +0x1e0, the
manoeuvre extents and the graph window's record at +0x280.  The
reimplementation keeps that layout so the harness can compare the whole
image.  Its relocations are eighteen code pointers (zeroed here and
installed by analysis.c) and five pointers into the image itself (likewise).

The second file carries the nine doubles at the start of .rdata.

Usage: tools/gen_analysis_data.py [orig/Modules/ANALYSIS.DLL]
                                  [src/analysis/analysis_data.inc]
                                  [src/analysis/analysis_rdata.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/ANALYSIS.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/analysis/analysis_data.inc"
RDS = sys.argv[3] if len(sys.argv) > 3 else "src/analysis/analysis_rdata.inc"

BASE = 0x20630000
DATA_VA = 0x20634000
RDATA_VA = 0x20633000
TEXT_END = 0x20632F96
SIZE = 0x32C
IMPORTS = 0x088
LINKAGE = 0x0C8
CONSTANTS = 0x48

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * i) for i in range(8)] == \
    [1, 2, 4, 13, 14, 17, 20, 0], "ImportTable"
assert u32(LINKAGE) == 29, "module id"
assert bytes(data[0x70:0x82]) == bytes.fromhex(
    "000100050e1d32000000fa000000f4010000"), "countdown and tables"
assert data[0x108:0x113] == b"V_VELOCITY\0" and data[0x168:0x16b] == b"+0\0", "strings"
assert data[0x178:0x185] == b"Scale String\0", "the scale's text"
assert [u32(0x1E0 + 4 * i) for i in range(15)] == \
    [0, 8, 0x2001, 0x20632D90, 0, 1, 0x30, 0x2005, 0x828, 1,
     1, 0x38, 0x2005, 0x824, 1], "exchange table"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size

CODE = [LINKAGE + 4, LINKAGE + 8] + [LINKAGE + 0x18 + 4 * i for i in range(10)] + \
       [0x14C, 0x150, 0x18C, 0x190, 0x1A4, 0x1EC]
SELF = {0x158: 0x108, 0x15C: 0x118, 0x160: 0x128, 0x164: 0x138, 0x19C: 0x179}
assert sorted(relocations) == sorted(CODE + list(SELF)), "relocation layout changed"

for offset in CODE:
    assert BASE + 0x1000 <= u32(offset) < TEXT_END, "relocation points outside .text"
    data[offset:offset + 4] = bytes(4)
for offset, target in SELF.items():
    assert u32(offset) == DATA_VA + target, "self pointer moved"
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_analysis_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * ANALYSIS's complete 0x32c-byte .data image, with its code pointers\n")
    output.write(" * and pointers into itself zeroed for analysis.c to install.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))

rva, virtual_size, raw_size, raw = sections[".rdata"]
assert BASE + rva == RDATA_VA, ".rdata moved"
rdata = blob[raw:raw + CONSTANTS]
constants = struct.unpack_from("<9d", rdata)
assert constants[0] == 0.5 and constants[3] == 512.0 and constants[5] == 2.0 ** -13, "constants"
assert constants[7] == -4096.0 and constants[8] == 3072.0, "the plot's offsets"

with open(RDS, "w") as output:
    output.write("/* Generated by tools/gen_analysis_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * ANALYSIS's .rdata constants, the nine doubles at +0x00..+0x47.\n */\n")
    for offset in range(0, CONSTANTS, 8):
        chunk = rdata[offset:offset + 8]
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%02x] = %s\n" % (offset, values))

print("wrote", DST, "and", RDS)
