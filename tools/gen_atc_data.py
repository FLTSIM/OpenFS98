#!/usr/bin/env python3
"""Extract ATC.DLL's initialised .data image into C.

ATC is hand-written assembly that keeps everything -- its ImportTable and
Linkage, the message templates it patches in place, the macro and handler
tables, its state -- in one .data section, addressed at fixed offsets.  The
reimplementation keeps one image laid out exactly the same way, so offsets in
a disassembly listing can be grepped for in the C directly.

This emits the bytes from +0x70 (after ImportTable and Linkage, which the C
defines itself) to the end of the initialised part; the rest of the section
is zero, as the loader leaves it.  Pointers inside the image stay as retail's
absolute addresses and are translated on use -- see ATC_PTR in atc.c.

The handler tables hold code addresses.  They are checked here against the
addresses atc.c's tables were transliterated from, so a mismatch is caught at
generation rather than as a wrong state transition.

Usage: tools/gen_atc_data.py [orig/Modules/ATC.DLL] [src/atc/atc_data.inc]
"""
import struct, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'orig/Modules/ATC.DLL'
DST = sys.argv[2] if len(sys.argv) > 2 else 'src/atc/atc_data.inc'

b = open(SRC, 'rb').read()
e = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, e + 6)[0]
base = struct.unpack_from('<I', b, e + 24 + 28)[0]
so = e + 24 + struct.unpack_from('<H', b, e + 20)[0]
secs = {}
for _ in range(nsec):
    name = b[so:so + 8].rstrip(b'\0').decode()
    vsz, va, rsz, ro = struct.unpack_from('<IIII', b, so + 8)
    secs[name] = (va, vsz, rsz, ro)
    so += 40

va, vsz, rsz, ro = secs['.data']
assert base + va == 0x20643000, 'ATC .data is not at 0x20643000'
assert vsz == 0x1a00, '.data virtual size changed'
data = b[ro:ro + min(rsz, vsz)]
u32 = lambda o: struct.unpack_from('<I', data, o)[0]

# Linkage, as atc.c's struct describes it.
assert u32(0x40) == 24
assert [u32(0x40 + 4 * i) for i in range(1, 11)] == [
    0x20641020, 0x2064102c, 0, 0, 0,
    0x2064176f, 0x2064173f, 0x20641038, 0x20641107, 0x20641b41], 'Linkage'
assert u32(0x6c) == 0

# The two state-machine handler tables, entry 0 through the last.
TAKEOFF = [0x2064185b, 0x2064189f, 0x206418b2, 0x20641a31, 0x20641906,
           0x2064192d, 0x20641970, 0x20641991, 0x2064189f, 0x206418dc,
           0x206419ec, 0x206418b2, 0x20641a55, 0x2064185b]
LANDING = [0x2064185b, 0x2064189f, 0x206418b2, 0x20641a0b, 0x20641ad4,
           0x2064185b]
assert [u32(0x739 + 4 * i) for i in range(len(TAKEOFF))] == TAKEOFF, 'takeoff table'
assert [u32(0x771 + 4 * i) for i in range(len(LANDING))] == LANDING, 'landing table'

# Spot checks on the strings atc.c names by offset.
for off, text in [(0x4fa, b' weather - '), (0x664, b'Microsoft Flight Simulator'),
                  (0x6af, b'7777 '), (0x6db, b' Measured ceiling '),
                  (0x735, b' LRC'), (0x934, b'%x'), (0x938, b'TRANSLATOR'),
                  (0x944, b'LocaleID'), (0x950, b'00000000'),
                  (0x95c, b'ATIS.XLT'), (0x968, b'A')]:
    assert data[off:off + len(text)] == text, hex(off)

body = data[0x70:]
with open(DST, 'w') as f:
    f.write('/* Generated by tools/gen_atc_data.py from %s -- do not edit.\n' % SRC)
    f.write(' *\n'
            ' * ATC\'s .data from +0x70 to +0x%x as the file holds it: message\n'
            ' * templates, the macro and handler tables, and initial state.  Pointers\n'
            ' * are retail\'s absolute addresses (.data at 0x20643000).\n'
            ' */\n' % len(data))
    for i in range(0, len(body), 16):
        f.write('    ' + ' '.join('0x%02x,' % c for c in body[i:i + 16]) + '\n')
