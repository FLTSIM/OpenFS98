#!/usr/bin/env python3
"""Extract BOOSTER.DLL's .data image into C.

BOOSTER keeps ImportTable at +0, Linkage at +0x38, then its strings, the
level factors and all of its state in one 0x904-byte .data section (0x200
bytes on disk, the rest zero).  The reimplementation keeps that layout so the
harness can compare the whole image.  The four Linkage code pointers are the
only relocations in it; they are zeroed here and installed by booster.c.

Usage: tools/gen_booster_data.py [orig/Modules/BOOSTER.DLL]
                                 [src/booster/booster_data.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/BOOSTER.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/booster/booster_data.inc"

BASE = 0x20650000
DATA_VA = 0x20654000
SIZE = 0x904
IMPORTS = 0x000
LINKAGE = 0x038

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * i) for i in range(7)] == [
    1, 2, 4, 17, 20, 18, 0
], "ImportTable"
assert all(u32(IMPORTS + 8 * i + 4) == 0 for i in range(7)), "import links"
assert u32(LINKAGE) == 34, "module id"
assert [u32(LINKAGE + offset) for offset in (0x0C, 0x10, 0x14)] == [0, 0, 0], \
    "Linkage header"
assert data[0x58:0x60] == b"bstinfo\0", "bstinfo name"
assert data[0xF0:0xFD] == b"FILES\0\0\0GRID\0", "source directory names"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size

linkage_relocations = [LINKAGE + 4, LINKAGE + 8, LINKAGE + 0x18, LINKAGE + 0x1C]
assert sorted(relocations) == linkage_relocations, "relocation layout changed"

for offset in relocations:
    assert 0x20651000 <= u32(offset) < 0x20653000, \
        "relocation is not a code pointer"
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_booster_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * BOOSTER's complete 0x904-byte .data image, with the Linkage code\n")
    output.write(" * pointers zeroed for booster.c to install.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))

print("wrote", DST)
