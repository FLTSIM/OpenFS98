#!/usr/bin/env python3
"""Extract DEMO.DLL's .data image into C.

DEMO keeps ImportTable at +0, Linkage at +0x50, then all of its state and
tables in one 0x1165-byte .data section (0x1000 bytes on disk, the rest
zero).  The reimplementation keeps that layout so the harness can compare the
whole image.  Its 98 relocations are code pointers (the Linkage, the reader
table at +0x610, the three handler tables, the dialog callbacks) and five
pointers into .data; all are zeroed here and installed by demo.c.

Usage: tools/gen_demo_data.py [orig/Modules/DEMO.DLL]
                                 [src/demo/demo_data.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/DEMO.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/demo/demo_data.inc"

BASE = 0x20690000
DATA_VA = 0x20697000
SIZE = 0x1165
IMPORTS = 0x000
LINKAGE = 0x050

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * i) for i in range(10)] == [
    1, 2, 4, 16, 3, 17, 39, 20, 22, 0
], "ImportTable"
assert all(u32(IMPORTS + 8 * i + 4) == 0 for i in range(10)), "import links"
assert u32(LINKAGE) == 7, "module id"
assert [u32(LINKAGE + offset) for offset in (0x0C, 0x10, 0x14)] == [0, 0, 0], \
    "Linkage header"
assert data[0x7C0:0x7C5] == bytes([0x9B, 0x9A, 0x98, 0x99, 0x99]), "rate tags"
assert data[0x7F7:0x7FB] == b"%%s:", "sound cue"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size

expected = ([LINKAGE + 4, LINKAGE + 8] +
            [LINKAGE + 0x18 + 4 * i for i in range(10)] +
            [0x610 + 4 * i for i in range(10)] +
            [0x63C + 4 * i for i in range(0x19)] +
            [0x6B4 + 4 * i for i in range(0x17)] +
            [0x710 + 4 * i for i in range(0x14)] +
            [0xE84, 0xEA4, 0xEA8, 0xEC0, 0xEC4, 0xED4, 0xEEC, 0xF00])
assert sorted(relocations) == sorted(expected), "relocation layout changed"

for offset in relocations:
    value = u32(offset)
    assert 0x20691000 <= value < 0x20696000 or \
        DATA_VA <= value < DATA_VA + SIZE, "relocation points outside"
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_demo_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * DEMO's complete 0x1165-byte .data image, with the relocated\n")
    output.write(" * pointers zeroed for demo.c to install.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))

print("wrote", DST)
