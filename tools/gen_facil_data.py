#!/usr/bin/env python3
"""Extract FACIL.DLL's .data image into C.

FACIL keeps its ImportTable, Linkage, dialog tables, constants and mutable
state in one .data section.  Only the first 0x600 bytes are present on disk;
the loader zero-fills the rest to 0x2d1c bytes.  The reimplementation keeps
the same layout so the retail offsets remain useful evidence.

Relocated pointers in the initialized prefix are emitted separately.  Pointers
into .data can be recreated mechanically.  Pointers into .text name dialog
handlers or retail entry points and must be supplied by facil.c.

Usage: tools/gen_facil_data.py [orig/Modules/facil.dll]
                               [src/facil/facil_data.inc]
"""
import struct
import sys


SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/facil.dll"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/facil/facil_data.inc"

BASE = 0x206B0000
DATA_VA = 0x206B8000
SIZE = 0x2D1C
RAW_SIZE = 0x600
IMPORTS = 0x0000
LINKAGE = 0x0040
LINKAGE_END = 0x0074


blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA, ".data moved"
assert virtual_size == SIZE and raw_size == RAW_SIZE, ".data resized"
data = bytearray(blob[raw:raw + raw_size])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * index) for index in range(8)] == [
    1, 2, 4, 18, 3, 17, 20, 0
], "ImportTable"
assert all(u32(IMPORTS + 8 * index + 4) == 0 for index in range(8)), \
    "import links"
assert u32(LINKAGE) == 37, "module id"
assert [u32(LINKAGE + offset) for offset in (0x0C, 0x10, 0x14)] == [0, 0, 0], \
    "Linkage header"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        kind = entry >> 12
        if kind == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert kind == 0, "unexpected relocation type"
    cursor += block_size

assert len(relocations) == 74, "relocation layout changed"
assert relocations[:9] == [
    LINKAGE + 4, LINKAGE + 8,
    LINKAGE + 0x18, LINKAGE + 0x1C, LINKAGE + 0x20,
    LINKAGE + 0x24, LINKAGE + 0x28, LINKAGE + 0x2C,
    LINKAGE + 0x30,
], "Linkage relocations"

text_rva, text_size = sections[".text"][:2]
text_va = BASE + text_rva
data_relocations = []
text_relocations = []
for offset in relocations:
    target = u32(offset)
    if DATA_VA <= target < DATA_VA + SIZE:
        data_relocations.append((offset, target - DATA_VA))
    else:
        assert text_va <= target < text_va + text_size, \
            "relocation outside .text and .data"
        text_relocations.append((offset, target - BASE))
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_facil_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * FACIL's complete 0x2d1c-byte .data image, with relocated\n")
    output.write(" * pointers zeroed and emitted as FACIL_REL_DATA/TEXT entries.\n")
    output.write(" */\n")
    output.write("#ifdef FACIL_RELOCS\n")
    for offset, target in data_relocations:
        output.write("    FACIL_REL_DATA(0x%04x, 0x%04x)\n" % (offset, target))
    for offset, target in text_relocations:
        output.write("    FACIL_REL_TEXT(0x%04x, 0x%04x)\n" % (offset, target))
    output.write("#else\n")
    for offset in range(LINKAGE_END, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x - FACIL_DATA_START] = %s\n" %
                     (offset, values))
    output.write("#endif\n")

print("wrote", DST)
