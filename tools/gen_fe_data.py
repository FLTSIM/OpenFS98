#!/usr/bin/env python3
"""Extract FE.DLL's .data image into C.

FE keeps its ImportTable, Linkage and all its state in one .data section --
0x3400 bytes on disk, 0x62e0 in memory, the rest zero -- and the
reimplementation keeps one image laid out the same way, because the code
addresses its state by retail's offsets.  The relocated dwords in it are the
Linkage, which fe.c fills with its own functions, and pointers elsewhere in
the image: a few to other places in .data, and the C half's dialog tables,
which point at code.  Those are emitted as a list for fe.c to apply when the
DLL attaches; the bytes under them are zero here.

One output, fe_data.inc:
  FE_DATA      the image from the end of the Linkage on, as bytes
  FE_RELOCS    FE_REL_DATA(offset, target) for each pointer into .data, and
               FE_REL_TEXT(offset, rva) for each pointer into .text

Usage: tools/gen_fe_data.py [orig/Modules/FE.DLL] [src/fe/fe_data.inc]
"""
import struct, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'orig/Modules/FE.DLL'
DST = sys.argv[2] if len(sys.argv) > 2 else 'src/fe/fe_data.inc'

DATA_VA = 0x206ce000
SIZE = 0x62e0
LINK = 0x48                 # the Linkage, after nine ImportTable entries
LINK_END = LINK + 0x8c      # its last slot is +0x88

b = open(SRC, 'rb').read()
e = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, e + 6)[0]
opt = e + 24
base = struct.unpack_from('<I', b, opt + 28)[0]
so = opt + struct.unpack_from('<H', b, e + 20)[0]
secs = {}
for _ in range(nsec):
    name = b[so:so + 8].rstrip(b'\0').decode()
    vsz, va, rsz, ro = struct.unpack_from('<IIII', b, so + 8)
    secs[name] = (va, vsz, rsz, ro)
    so += 40

va, vsz, rsz, ro = secs['.data']
assert base + va == DATA_VA and vsz == SIZE, '.data moved or resized'
data = bytearray(b[ro:ro + min(rsz, SIZE)] + bytes(max(0, SIZE - rsz)))
u32 = lambda o: struct.unpack_from('<I', data, o)[0]
tva, tvsz = secs['.text'][:2]
TEXT_VA = base + tva

rva, rvsz, rrsz, rro = secs['.reloc']
r = b[rro:rro + rvsz]
relocs, i = set(), 0
while i + 8 <= len(r):
    page, sz = struct.unpack_from('<II', r, i)
    if sz == 0:
        break
    for j in range(8, sz, 2):
        ent = struct.unpack_from('<H', r, i + j)[0]
        if ent >> 12 == 3:
            relocs.add(base + page + (ent & 0xfff))
        else:
            assert ent >> 12 == 0, 'unexpected relocation type'
    i += sz
drel = sorted(a - DATA_VA for a in relocs if DATA_VA <= a < DATA_VA + SIZE)

# ImportTable: host, GLOBAL, BOOSTER, CHAIN, FACIL, G3D, NUMERIC, UTIL, end.
assert [u32(8 * k) for k in range(9)] == [1, 2, 34, 4, 37, 14, 17, 20, 0], 'ImportTable'
assert all(u32(8 * k + 4) == 0 for k in range(9)), 'ImportTable links'

# Linkage: id 18, init, deinit, 0, 0xd0000000 (where dumplinkage.py stops),
# 0, then the 29 slots +0x18..+0x88.
assert u32(LINK) == 18, 'module id'
assert (u32(LINK + 4), u32(LINK + 8)) == (0x206c1020, 0x206c10ed), 'init/deinit'
assert [u32(LINK + o) for o in (0x0c, 0x10, 0x14)] == [0, 0xd0000000, 0], 'Linkage header'
slots = [u32(LINK + 0x18 + 4 * k) for k in range(29)]
assert all(TEXT_VA <= a < TEXT_VA + tvsz for a in slots), 'slot outside .text'
assert not any(data[LINK_END:LINK + 0xc4]), 'Linkage tail'

link_rel = [o for o in drel if o < LINK_END]
assert link_rel == [LINK + 4, LINK + 8] + [LINK + 0x18 + 4 * k for k in range(29)], 'Linkage relocations'
rest = [o for o in drel if o >= LINK_END]
assert len(rest) == 86 - 31, 'relocation count'

out_rel = []
for o in rest:
    v = u32(o)
    if DATA_VA <= v < DATA_VA + SIZE:
        out_rel.append('FE_REL_DATA(0x%04x, 0x%04x)' % (o, v - DATA_VA))
    else:
        assert TEXT_VA <= v < TEXT_VA + tvsz, 'pointer at +%x outside .text and .data' % o
        out_rel.append('FE_REL_TEXT(0x%04x, 0x%04x)' % (o, v - base))
    data[o:o + 4] = bytes(4)

with open(DST, 'w') as f:
    f.write('/* Generated by tools/gen_fe_data.py from %s -- do not edit.\n' % SRC)
    f.write(' *\n * FE\'s .data from the end of the Linkage (+0x%x) to +0x%x, with every\n' % (LINK_END, SIZE))
    f.write(' * relocated dword zeroed, and those dwords as a list: FE_REL_DATA for a\n')
    f.write(' * pointer into the image (its target offset), FE_REL_TEXT for one into\n')
    f.write(' * code (retail\'s RVA).\n */\n')
    f.write('#ifdef FE_RELOCS\n')
    for line in out_rel:
        f.write('    %s\n' % line)
    f.write('#else\n')
    for o in range(LINK_END, SIZE, 16):
        chunk = data[o:min(o + 16, SIZE)]
        if not any(chunk):
            continue
        f.write('    [0x%04x - FE_DATA_START] = %s\n' % (o, ' '.join('0x%02x,' % x for x in chunk)))
    f.write('#endif\n')
print('wrote', DST)
