#!/usr/bin/env python3
"""Transcribe G3D's mesh compiler (opcode 0x38, .text+0x28d0..+0x361a)
instruction for instruction into GAS (src/g3d/g3d_mesh.S).

The block is compiled C that triangulates polygons in single-precision
floats on the x87: whether a vertex is an ear turns on the sign of a float
sum, and which intermediates MSVC rounded to floats (stored) and which it
kept at extended precision decides it.  C compiled by another compiler does
not reproduce that, so the block is carried over as its own instructions:
jumps and calls inside it become labels, .data references become references
into OpenFS98's image of it (_g3d_image), the .rdata constants it reads and
its dispatch tables are copied, the call to the host's +0x64 sibling
(0x206e2850) goes to OpenFS98's, and MSVCRT's _CIacos (the CD's) is
transcribed by hand below.  A portable C version, for builds without an
x87, is still to come and will be checked against this one.

Usage: tools/gen_g3d_mesh.py orig/Modules/G3D.DLL src/g3d/g3d_mesh.S
"""
import re
import struct
import subprocess
import sys

START, END = 0x206e28d0, 0x206e361a
JUMP_TABLE, BYTE_TABLE, BYTE_TABLE_LEN = 0x206e361c, 0x206e363c, 0x7d
RDATA, RDATA_LEN = 0x206f8000, 0x38
DATA_VA, DATA_END = 0x206f9000, 0x206f9000 + 0x18450
ENTRIES = {0x206e35b0: ("_g3d_compile_mesh@4", "0x38's pass over the instruction after it")}
EXTERNAL = {0x206e2850: "_next_instruction", 0x206f7960: "_g3d_acos_cd"}


def sections(dll):
    pe = struct.unpack_from("<I", dll, 0x3c)[0]
    base = struct.unpack_from("<I", dll, pe + 0x34)[0]
    n = struct.unpack_from("<H", dll, pe + 6)[0]
    opt = struct.unpack_from("<H", dll, pe + 20)[0]
    out = []
    for i in range(n):
        o = pe + 24 + opt + 40 * i
        size, va, rsize, raw = struct.unpack_from("<4I", dll, o + 8)
        out.append((base + va, max(size, rsize), raw))
    return out


def read(dll, secs, addr, n):
    for va, size, raw in secs:
        if va <= addr and addr + n <= va + size:
            return dll[raw + addr - va:raw + addr - va + n]
    raise SystemExit("0x%08x not in a section" % addr)


def label(a):
    return "L_%08x" % a


def convert(text):
    """objdump's Intel operands to GAS's."""
    m = re.match(r"(call|j[a-z]+)\s+0x([0-9a-f]+)$", text)
    if m:
        t = int(m.group(2), 16)
        if t in EXTERNAL:
            return "%s %s" % (m.group(1), EXTERNAL[t])
        if not START <= t < END:
            raise SystemExit("branch out of the block: " + text)
        return "%s %s" % (m.group(1), label(t))

    def ds(mm):
        a = int(mm.group(1), 16)
        if DATA_VA <= a < DATA_END:
            return "[_g3d_image+0x%x]" % (a - DATA_VA)
        if RDATA <= a < RDATA + RDATA_LEN:
            return "[_g3d_mesh_rdata+0x%x]" % (a - RDATA)
        raise SystemExit("data out of reach: " + text)
    text = re.sub(r"ds:0x([0-9a-f]+)", ds, text)
    text = text.replace("+0x%x]" % JUMP_TABLE, "+L_jump_table]")
    text = text.replace("+0x%x]" % BYTE_TABLE, "+L_byte_table]")
    if re.search(r"0x206[ef][0-9a-f]{4}", text):
        raise SystemExit("unconverted address: " + text)
    return text


def main():
    dll_path, out_path = sys.argv[1], sys.argv[2]
    dll = open(dll_path, "rb").read()
    secs = sections(dll)
    dis = subprocess.run(["objdump", "-d", "--no-show-raw-insn", "-M", "intel",
                          "--start-address=0x%x" % START, "--stop-address=0x%x" % END,
                          dll_path], capture_output=True, text=True, check=True).stdout
    lines = []
    for ln in dis.splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s+(.*\S)\s*$", ln)
        if m:
            lines.append((int(m.group(1), 16), m.group(2)))
    targets = set()
    for a, t in lines:
        m = re.match(r"(?:call|j[a-z]+)\s+0x([0-9a-f]+)$", t)
        if m:
            targets.add(int(m.group(1), 16))
    jt = struct.unpack("<8I", read(dll, secs, JUMP_TABLE, 32))
    targets.update(jt)
    targets.update(ENTRIES)
    out = ["/* Generated by tools/gen_g3d_mesh.py from orig/Modules/G3D.DLL -- do not edit.",
           " * G3D's mesh compiler (0x38), .text+0x28d0..+0x361a, instruction for",
           " * instruction; see the generator for why. */",
           "\t.intel_syntax noprefix", "\t.text"]
    for a, (name, what) in ENTRIES.items():
        out.append("\t.globl %s\t\t/* 0x%08x, %s */" % (name, a, what))
    for a, t in lines:
        if a in ENTRIES:
            out.append("%s:" % ENTRIES[a][0])
        if a in targets:
            out.append("%s:" % label(a))
        if t.startswith("(bad)") or t.startswith("."):
            continue
        out.append("\t%s\t\t/* %08x */" % (convert(t), a))
    out.append("")
    out.append("/* MSVCRT's _CIacos, the CD's (MSVCRT.DLL 0x7802e6a3): st0 in, st0 out,")
    out.append(" * |x| < 1 only (G3D's caller takes the ends itself).  The control word")
    out.append(" * keeps its precision, rounds to nearest and masks every exception while")
    out.append(" * it works, and is put back after; the branch that raises an unmasked")
    out.append(" * inexact result is left out (OpenFS98 never unmasks it). */")
    out += ["_g3d_acos_cd:",
            "\tpush edx",
            "\tfstcw WORD PTR [esp]",
            "\tmov edx, DWORD PTR [esp]",
            "\tcmp dx, 0x27f",
            "\tje 1f",
            "\tand edx, 0x300",
            "\tor edx, 0x7f",
            "\tmov WORD PTR [esp+2], dx",
            "\tfldcw WORD PTR [esp+2]",
            "1:\tfld1",
            "\tfadd st, st(1)",
            "\tfld1",
            "\tfsub st, st(2)",
            "\tfmulp st(1), st",
            "\tfsqrt",
            "\tfxch st(1)",
            "\tfpatan",
            "\tfldcw WORD PTR [esp]",
            "\tpop edx",
            "\tret",
            ""]
    out.append("\t.section .rdata")
    out.append("\t.p2align 2")
    out.append("_g3d_mesh_rdata:\t\t/* 0x%08x.. */" % RDATA)
    out.append("\t.byte " + ",".join("0x%02x" % b for b in read(dll, secs, RDATA, RDATA_LEN)))
    out.append("L_jump_table:\t\t/* 0x%08x */" % JUMP_TABLE)
    for t in jt:
        out.append("\t.long %s" % label(t))
    out.append("L_byte_table:\t\t/* 0x%08x */" % BYTE_TABLE)
    out.append("\t.byte " + ",".join("0x%02x" % b for b in read(dll, secs, BYTE_TABLE, BYTE_TABLE_LEN)))
    out.append("")
    open(out_path, "w").write("\n".join(out))


if __name__ == "__main__":
    main()
