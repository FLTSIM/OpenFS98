#!/usr/bin/env python3
"""Regenerate src/global/global_state.inc from the retail GLOBAL.DLL.

GLOBAL's whole payload is its 4776 byte .data block: the shared state every
other module reads as byte offsets from the Linkage pointer.  Only 203 of
those bytes are non-zero in the image, and those are the power-on defaults.
This emits them as C99 designated initializers keyed by their *absolute*
offset in the block, so an offset seen in a disassembly listing can be found
in the .inc by searching for the same number.
"""
import struct, sys

SRC  = sys.argv[1] if len(sys.argv) > 1 else 'orig/Modules/GLOBAL.DLL'
DST  = sys.argv[2] if len(sys.argv) > 2 else 'src/global/global_state.inc'
HEAD = 0x0c          # id + init + deinit, emitted as named fields instead

b = open(SRC, 'rb').read()
e = struct.unpack_from('<I', b, 0x3c)[0]
nsec   = struct.unpack_from('<H', b, e + 6)[0]
optsz  = struct.unpack_from('<H', b, e + 20)[0]
so = e + 24 + optsz
data = None
for i in range(nsec):
    name = b[so:so + 8].rstrip(b'\0').decode()
    vsz, va, rsz, ro = struct.unpack_from('<IIII', b, so + 8)
    if name == '.data':
        data = b[ro:ro + vsz]
        size = vsz
    so += 40
if data is None:
    sys.exit('no .data section in ' + SRC)

with open(DST, 'w') as f:
    f.write('/* Generated by tools/gen_global_state.py from %s -- do not edit. */\n'
            % SRC)
    f.write('/* %d byte shared state block; %d non-zero default bytes. */\n\n'
            % (size, sum(1 for c in data if c)))
    f.write('#define FS98_GLOBAL_SIZE 0x%x\n' % size)
    f.write('#define FS98_GLOBAL_HEAD 0x%x\n\n' % HEAD)
    f.write('#define FS98_GLOBAL_DEFAULTS \\\n')
    for off in range(HEAD, size):
        if data[off]:
            f.write('    [0x%04x - FS98_GLOBAL_HEAD] = 0x%02x, \\\n' % (off, data[off]))
    f.write('    /* rest implicitly zero */\n')
print('wrote %s' % DST)
