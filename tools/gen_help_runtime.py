#!/usr/bin/env python3
"""Extract Help's vtable bindings and build-only Windows resources.

No machine code or resource payload is written to tracked source. The include
contains ABI metadata; the .res and ordinal anchor go under ignored bin/.
"""
from pathlib import Path
import struct
import sys

from dialogmap import Fs98Pe, SurveyError


def resource_name(name):
    if isinstance(name, int):
        if name > 0xffff:
            raise SurveyError('resource ordinal exceeds WORD')
        return struct.pack('<HH', 0xffff, name)
    return name.encode('utf-16-le') + b'\0\0'


def main():
    pe = Fs98Pe(sys.argv[1] if len(sys.argv) > 1 else 'orig/English/Help.DLL')
    if pe.uiBase != 0x22330000 or pe.linkage()['id'] != 0x80000008:
        raise SurveyError('expected the reference Help image at 0x22330000')
    directory = Path('bin/help-diff')
    directory.mkdir(parents=True, exist_ok=True)
    imports = [binding for binding in pe.imports()
                if binding['dll'].upper() in ('SIMSUI.DLL', 'MFC42.DLL')]
    import_indices = {binding['iat_va']: index for index, binding in enumerate(imports)}
    local = {
        0x1510: 'fs98_help_about_delete', 0x1c30: 'fs98_help_credits_delete',
        0x2370: 'fs98_help_lessons_delete', 0x2b50: 'fs98_help_graph_delete',
        0x2eb0: 'fs98_help_completion_delete', 0x2260: 'fs98_help_placeholder_delete',
        0x2250: 'fs98_help_empty_arg', 0x1b40: 'fs98_help_empty',
        0x1b50: 'fs98_help_disable', 0x1b60: 'fs98_help_enable', 0x2760: 'fs98_help_post_destroy',
        0x1620: 'fs98_help_about_exchange', 0x1ce0: 'fs98_help_credits_exchange',
        0x2480: 'fs98_help_lessons_exchange', 0x2be0: 'fs98_help_graph_exchange',
        0x2f50: 'fs98_help_completion_exchange',
        0x1700: 'help_map_about', 0x1d40: 'help_map_credits', 0x2560: 'help_map_lessons',
        0x2c10: 'help_map_graph', 0x2f90: 'help_map_completion',
        0x1710: 'fs98_help_about_init', 0x1d50: 'fs98_help_credits_init',
        0x2570: 'fs98_help_lessons_init', 0x2ca0: 'fs98_help_graph_init',
        0x2fa0: 'fs98_help_completion_init',
        0x18e0: 'fs98_help_about_accept', 0x18c0: 'fs98_help_about_cancel',
        0x1f80: 'fs98_help_credits_accept', 0x1f60: 'fs98_help_credits_cancel',
        0x2790: 'fs98_help_lessons_accept', 0x2770: 'fs98_help_lessons_cancel',
        0x2c50: 'fs98_help_graph_accept', 0x3090: 'fs98_help_completion_accept',
        0x30b0: 'fs98_help_completion_cancel', 0x1ef0: 'fs98_help_credits_close',
        0x1900: 'fs98_help_about_credits', 0x1910: 'fs98_help_about_help',
        0x1930: 'fs98_help_about_context', 0x2180: 'fs98_help_credits_timer',
        0x21f0: 'fs98_help_credits_toggle', 0x1fa0: 'fs98_help_credits_help',
        0x1fc0: 'fs98_help_credits_context', 0x2950: 'fs98_help_lessons_select',
        0x2a80: 'fs98_help_lessons_double_click', 0x2aa0: 'fs98_help_lessons_help',
        0x2ac0: 'fs98_help_lessons_context', 0x2da0: 'fs98_help_graph_help',
        0x2dc0: 'fs98_help_graph_context', 0x2c20: 'fs98_help_graph_tick',
        0x30d0: 'fs98_help_completion_help', 0x30f0: 'fs98_help_completion_context',
    }
    lines = ['/* Generated by tools/gen_help_runtime.py; ABI metadata only. */',
              'static const struct help_import_binding s_import_bindings[] = {']
    for binding in imports:
        name = binding['name']
        ordinal = int(name[1:]) if name.startswith('#') else 0
        lines.append(f'    {{"{binding["dll"]}", "{name}", {ordinal}, 0x{binding["iat_va"] - pe.uiBase:x}}},')
    lines += ['};', 'static const struct help_virtual_binding s_virtual_bindings[] = {']
    for table, (rva, count) in enumerate(((0x40c8, 60), (0x4260, 60), (0x44e8, 60), (0x4660, 60), (0x47c0, 60), (0x4350, 48))):
        for slot in range(count):
            function = pe.va_uint32(pe.uiBase + rva + slot * 4)
            function_rva = function - pe.uiBase
            if function_rva in local:
                entry_literal = f'-1, (void *){local[function_rva]}'
            else:
                offset = pe.file_offset(function_rva, 6)
                if pe.read_bytes(offset, 2) != b'\xff\x25':
                    raise SurveyError(f'unrecognised vtable target {function:#x}')
                iat = pe.read_uint32(offset + 2)
                if iat not in import_indices:
                    raise SurveyError('vtable target is not a declared MFC/SIMSUI import')
                entry_literal = f'{import_indices[iat]}, 0'
            lines.append(f'    {{{table}, {slot}, {entry_literal}}},')
    lines += ['};']
    for name, map in (('about', 0x4060), ('credits', 0x41e0), ('lessons', 0x4468), ('graph', 0x45f8), ('completion', 0x4770)):
        lines.append(f'static const struct help_message_entry s_{name.lower()}_messages[] = {{')
        entry_addr = pe.va_uint32(pe.uiBase + map + 4)
        for index in range(64):
            fields = [pe.va_uint32(entry_addr + index * 24 + field * 4) for field in range(6)]
            if not any(fields):
                lines.append('    {0, 0, 0, 0, 0, 0}')
                break
            handler = fields[5] - pe.uiBase
            if handler not in local:
                raise SurveyError(f'unrecognised message handler {handler:#x}')
            field_literals = ', '.join(f'0x{value:x}' for value in fields[:5])
            lines.append(f'    {{{field_literals}, (void *){local[handler]}}},')
        else:
            raise SurveyError('unterminated message map')
        lines.append('};')
    lines.append('static const struct help_dialog s_dialogs[] = {')
    factories = {0x11c0: 'fs98_help_about_create', 0x1250: 'fs98_help_credits_create', 0x1130: 'fs98_help_lessons_create', 0x12e0: 'fs98_help_graph_create', 0x1370: 'fs98_help_completion_create'}
    for dialog in pe.linkage()['dialogs']:
        factory = dialog['create_va'] - pe.uiBase
        lines.append(f'    {{{dialog["id"]}, {factories[factory]}, {dialog["flags"]}}},')
    lines += ['    {0, 0, 0}', '};', '']
    Path('src/help/help_runtime_tables.inc').write_text('\n'.join(lines))

    # A PE import by ordinal is enough to make the loader resolve SIMSUI and
    # its MFC dependency before our DllMain, without C++ symbol aliases.
    ui = Fs98Pe('orig/SIMSUI.DLL')
    export = ui.file_offset(ui.directory(0)[0], 40)
    base = ui.read_uint32(export + 16)
    names_rva = ui.read_uint32(export + 32)
    ordinals_rva = ui.read_uint32(export + 36)
    anchor_ordinal = None
    for index in range(ui.read_uint32(export + 24)):
        name_rva = ui.read_uint32(ui.file_offset(names_rva + index * 4, 4))
        if ui.c_string(name_rva) == '?ui_new@@YAPAXI@Z':
            anchor_ordinal = base + ui.read_uint16(ui.file_offset(ordinals_rva + index * 2, 2))
    if anchor_ordinal is None:
        raise SurveyError('SIMSUI ui_new export missing')
    (directory / 'simsui-anchor.def').write_text(
        f'LIBRARY SIMSUI.DLL\nEXPORTS\n    fs98_help_simsui_anchor @{anchor_ordinal} NONAME\n')

    resources = bytearray(struct.pack('<IIHHHHIHHII', 0, 32, 0xffff, 0, 0xffff, 0, 0, 0, 0, 0, 0))
    for resource in pe.resources():
        if resource['type'] == 16:
            continue  # Do not copy the retail company's version resource.
        resource_names = resource_name(resource['type']) + resource_name(resource['id'])
        resource_names += b'\0' * (-len(resource_names) % 4)
        header = struct.pack('<II', resource['size'], 8 + len(resource_names) + 16)
        header += resource_names + struct.pack('<IHHII', 0, 0x1030, resource['language'], 0, 0)
        resources += header
        resources += pe.read_bytes(pe.file_offset(resource['rva'], resource['size']), resource['size'])
        resources += b'\0' * (-len(resources) % 4)
    (directory / 'help.res').write_bytes(resources)


if __name__ == '__main__':
    main()
