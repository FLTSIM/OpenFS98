#!/usr/bin/env python3
"""Extract HG2D's data and relocation map; no retail code is copied."""
import pathlib
import struct

source = pathlib.Path('orig/Modules/HG2D.DLL')
blob = source.read_bytes()
pe = struct.unpack_from('<I', blob, 0x3c)[0]
optional = pe + 24
assert struct.unpack_from('<I', blob, optional + 28)[0] == 0x20730000
section = optional + struct.unpack_from('<H', blob, pe + 20)[0]
sections = {}
for index in range(struct.unpack_from('<H', blob, pe + 6)[0]):
    offset = section + index * 40
    name = blob[offset:offset + 8].rstrip(b'\0').decode()
    sections[name] = struct.unpack_from('<IIII', blob, offset + 8)
size, rva, raw_size, raw = sections['.data']
assert (rva, size) == (0x62000, 0x28cd0)
data = bytearray(blob[raw:raw + raw_size]) + bytearray(size - raw_size)
def word(offset):
    return struct.unpack_from('<I', data, offset)[0]
assert [word(index * 8) for index in range(7)] == [1, 2, 4, 18, 20, 14, 0]
assert word(0x38) == 13
# The table ends at +0xbc. The mapper overruns its trailing zero padding.
assert word(0x38 + 0xbc) == 0x2078b760
relocation_size, _, _, relocation_raw = sections['.reloc']
cursor = relocation_raw
pointers = []
while cursor < relocation_raw + relocation_size:
    page, block_size = struct.unpack_from('<II', blob, cursor)
    if block_size == 0:
        break
    assert block_size >= 8
    for offset in range(cursor + 8, cursor + block_size, 2):
        entry = struct.unpack_from('<H', blob, offset)[0]
        assert entry >> 12 in (0, 3)
        address = page + (entry & 0xfff)
        if entry >> 12 == 3 and rva <= address < rva + size:
            at = address - rva
            value = word(at)
            if rva + 0x20730000 <= value < rva + 0x20730000 + size:
                pointers.append((at, value - 0x20792000))
                struct.pack_into('<I', data, at, 0)
            elif 0x38 <= at < 0xf8:
                struct.pack_into('<I', data, at, 0)
            else:
                assert 0x20731000 <= value < 0x20790266
    cursor += block_size
header = '/* Generated by tools/gen_hg2d_data.py from retail HG2D.DLL; do not edit. */\n'
with open('src/hg2d/hg2d_data.inc', 'w') as output:
    output.write(header)
    for offset in range(0, size, 16):
        chunk = data[offset:offset + 16]
        if any(chunk):
            output.write('    [0x%05x] = %s\n' % (offset, ' '.join('0x%02x,' % value for value in chunk)))
with open('src/hg2d/hg2d_pointers.inc', 'w') as output:
    output.write(header)
    for at, target in sorted(pointers):
        output.write('HG2D_DATA_POINTER(0x%05x, 0x%05x)\n' % (at, target))
print('HG2D: %#x data bytes, %d data pointers' % (size, len(pointers)))

# Tail dispatch tables are data embedded in .text, not executable bytes.
_, text_rva, _, text_raw = sections['.text']
with open('src/hg2d/hg2d_projective_tables.inc', 'w') as output:
    output.write(header)
    tables = (
        ('projective_tails', ((0x2073460b, 0x20734f16), (0x20737f6b, 0x20738875))),
        ('projective_key_fog_tails', ((0x2073cefb, 0x2073db57), (0x20740268, 0x20740ec4))),
        ('projective_fog_tails', ((0x207361ed, 0x20736f81), (0x20739b4a, 0x2073a8de))),
        ('projective_key_tails', ((0x2073b69a, 0x2073bf7c), (0x2073ea09, 0x2073f2eb))),
    )
    for name, pairs in tables:
        output.write('static const uint32_t %s[2][2][32] = {\n' % name)
        for pair in pairs:
            output.write('    {\n')
            for address in pair:
                values = struct.unpack_from('<32I', blob, text_raw + address - 0x20730000 - text_rva)
                assert all(0x20731000 <= value < 0x20790266 for value in values)
                output.write('        {\n')
                for index in range(0, 32, 4):
                    output.write('            ' + ', '.join('0x%08xu' % value for value in values[index:index+4]) + ',\n')
                output.write('        },\n')
            output.write('    },\n')
        output.write('};\n')

    dither_tables = (
        ('projective_dither_tails', (
            ((0x2074c11e, 0x2074ac87), (0x2074de1a, 0x2074cf93)),
            ((0x20756573, 0x207550dd), (0x2075826d, 0x207573e7)),
        )),
        ('projective_dither_fog_tails', (
            ((0x20751357, 0x2074f844), (0x2075394b, 0x20752648)),
            ((0x2075b7a8, 0x20759c95), (0x2075dd9c, 0x2075ca99)),
        )),
    )
    for name, tables in dither_tables:
        output.write('static const uint32_t %s[2][2][2][33] = {\n' % name)
        for directions in tables:
            output.write('    {\n')
            for phases in directions:
                output.write('        {\n')
                for address in phases:
                    values = struct.unpack_from('<33I', blob, text_raw + address - 0x20730000 - text_rva)
                    assert all(0x20731000 <= value < 0x20790266 for value in values)
                    output.write('            {\n')
                    for index in range(0, 33, 4):
                        output.write('                ' + ', '.join('0x%08xu' % value for value in values[index:index+4]) + ',\n')
                    output.write('            },\n')
                output.write('        },\n')
            output.write('    },\n')
        output.write('};\n')
