#!/usr/bin/env python3
"""Extract FLTSIM98.EXE's .data image into C for the HOST reimplementation.

HOST is module id 1, the host itself: FLTSIM98.EXE, base 0x400000, relocations
stripped.  It publishes a 0x320-byte service table at 0x417ba0 (a dword 1 then
194 slots) and keeps its state in .data, which runs from 0x417000 for a virtual
0x55cc bytes (0x1600 on disk, the rest zero).  The reimplementation keeps that
layout so hostdiff can compare the whole .data image against the real host,
which it maps at 0x400000 and runs in process.

Two outputs:
- host_data.inc: the .data bytes (disk bytes then zero-fill to the virtual
  size), as a C initialiser for a byte array at retail's offsets.
- host_pointers.inc: retail's service-table slot values (absolute code
  addresses in 0x4xxxxx), as MACRO(slot, addr) lines, so host.c can be checked
  against the table it is reimplementing and the harness can drive any slot by
  its retail address.

Usage: tools/gen_host_data.py [orig/FLTSIM98.EXE] [src/host/host_data.inc]
                              [src/host/host_pointers.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/FLTSIM98.EXE"
DATA = sys.argv[2] if len(sys.argv) > 2 else "src/host/host_data.inc"
PTRS = sys.argv[3] if len(sys.argv) > 3 else "src/host/host_pointers.inc"

BASE = 0x400000
DATA_VA = 0x417000
TABLE_VA = 0x417ba0
N_SLOTS = 0xc8            # 0x320 / 4 = 200 dwords (slot 0 is the id 1)


def main():
    b = open(SRC, "rb").read()
    pe = struct.unpack_from("<I", b, 0x3c)[0]
    nsec = struct.unpack_from("<H", b, pe + 6)[0]
    o = pe + 24 + struct.unpack_from("<H", b, pe + 20)[0]
    data_vs = data_raw = data_rs = None
    for _ in range(nsec):
        name = b[o:o + 8].rstrip(b"\0")
        va = struct.unpack_from("<I", b, o + 12)[0]
        if name == b".data":
            data_vs = struct.unpack_from("<I", b, o + 8)[0]
            data_rs = struct.unpack_from("<I", b, o + 16)[0]
            data_raw = struct.unpack_from("<I", b, o + 20)[0]
        o += 40
    if data_vs is None:
        raise SystemExit("no .data section")

    img = bytearray(b[data_raw:data_raw + data_rs])
    img += bytes(data_vs - len(img))       # zero-fill to the virtual size

    with open(DATA, "w") as f:
        f.write("/* FLTSIM98.EXE .data at 0x%x, virtual 0x%x bytes "
                "(0x%x on disk, the rest zero).  Generated by\n"
                " * tools/gen_host_data.py -- do not edit. */\n"
                % (DATA_VA, data_vs, data_rs))
        for i in range(0, len(img), 16):
            f.write("    " + "".join("0x%02x," % c for c in img[i:i + 16]) + "\n")

    table = img[TABLE_VA - DATA_VA: TABLE_VA - DATA_VA + N_SLOTS * 4]
    with open(PTRS, "w") as f:
        f.write("/* FLTSIM98.EXE's service table at 0x%x: slot offset and the\n"
                " * retail code address it holds.  Generated by\n"
                " * tools/gen_host_data.py -- do not edit. */\n" % TABLE_VA)
        for i in range(N_SLOTS):
            v = struct.unpack_from("<I", table, i * 4)[0]
            f.write("HOST_SLOT(0x%03x, 0x%08x)\n" % (i * 4, v))

    print("host_data.inc: 0x%x bytes; host_pointers.inc: %d slots" % (len(img), N_SLOTS))


if __name__ == "__main__":
    main()
