#!/usr/bin/env python3
"""Extract LANDME.DLL's .data image into C.

LANDME keeps its state first, then ImportTable at +0x7f8 and Linkage at
+0x838, in one 0x854-byte .data section.  The reimplementation preserves that
layout because the retail code addresses every state field by its original
offset.  Relocated code pointers are installed by landme.c and are zeroed in
the generated bytes.

Usage: tools/gen_landme_data.py [orig/Modules/LANDME.DLL]
                                [src/landme/landme_data.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/LANDME.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/landme/landme_data.inc"

BASE = 0x207D0000
DATA_VA = 0x207D3000
SIZE = 0x854
IMPORTS = 0x7F8
LINKAGE = 0x838

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * i) for i in range(8)] == [
    1, 2, 3, 4, 18, 20, 22, 0
], "ImportTable"
assert all(u32(IMPORTS + 8 * i + 4) == 0 for i in range(8)), "import links"
assert u32(LINKAGE) == 26, "module id"
assert [u32(LINKAGE + offset) for offset in (0x0C, 0x10, 0x14)] == [0, 0, 0], \
    "Linkage header"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size

state_relocations = [
    0x08C, 0x090, 0x094, 0x098, 0x09C, 0x0A0, 0x0A4,
    0x683, 0x687, 0x693, 0x697, 0x6A3, 0x6A7, 0x6B3, 0x6B7,
    0x6C3, 0x6C7, 0x6D3, 0x6D7, 0x6E3, 0x6E7, 0x6F3, 0x6F7,
    0x703, 0x707, 0x713, 0x717, 0x723, 0x727, 0x733, 0x737,
]
linkage_relocations = [LINKAGE + 4, LINKAGE + 8, LINKAGE + 0x18]
assert sorted(relocations) == state_relocations + linkage_relocations, \
    "relocation layout changed"

for offset in relocations:
    assert 0x207D1000 <= u32(offset) < 0x207D2000, \
        "relocation is not a code pointer"
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_landme_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * LANDME's complete 0x854-byte .data image, with relocated code\n")
    output.write(" * pointers zeroed for landme.c to install.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))

print("wrote", DST)
