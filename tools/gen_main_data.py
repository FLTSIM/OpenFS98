#!/usr/bin/env python3
"""Extract MAIN.DLL's .data image into C.

MAIN keeps ImportTable at +0 (22 modules), Linkage at +0xc0 (50 slots),
then its tables and all of its state in one 0x2ee00-byte .data section
(0x8000 bytes on disk, the rest zero).  The reimplementation keeps that
layout so the harness can compare the whole image, as G3D's does.

Its relocations into .data are of two kinds, treated as G3D's are:

- pointers into .data itself.  The image is written with them zeroed, and
  a table of (offset, target) pairs is written beside it for main.c to
  install, so they point into its own image.
- code pointers.  These keep retail's values, except the Linkage's, which
  other modules call through and main.c installs.  The distinct targets
  are written out too, so main.c can check that it maps every one it
  calls through.

Usage: tools/gen_main_data.py [orig/Modules/MAIN.DLL] [src/main/main_data.inc]
                              [src/main/main_pointers.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/MAIN.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/main/main_data.inc"
PTR = sys.argv[3] if len(sys.argv) > 3 else "src/main/main_pointers.inc"

BASE = 0x207E0000
TEXT_VA = 0x207E1000
TEXT_SIZE = 0x1D360
DATA_VA = 0x20800000
SIZE = 0x2EE00
IMPORTS = 0x000
LINKAGE = 0x0C0
LINKAGE_SLOTS = 51

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, _, _ = sections[".text"]
assert BASE + rva == TEXT_VA and virtual_size == TEXT_SIZE, ".text moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * i) for i in range(23)] == [
    1, 2, 23, 21, 29, 24, 4, 16, 7, 6, 37, 18, 13, 14, 26, 35, 17, 15, 39,
    9, 20, 27, 10
], "ImportTable"
assert u32(IMPORTS + 8 * 23) == 0, "ImportTable end"
assert all(u32(IMPORTS + 8 * i + 4) == 0 for i in range(23)), "import links"
assert u32(LINKAGE) == 3, "module id"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size
relocations.sort()

linkage = {LINKAGE + 4 * i for i in range(LINKAGE_SLOTS)}
data_pointers = []
code_targets = set()
for offset in relocations:
    value = u32(offset)
    if DATA_VA <= value < DATA_VA + SIZE:
        data_pointers.append((offset, value - DATA_VA))
        data[offset:offset + 4] = bytes(4)
    elif TEXT_VA <= value < TEXT_VA + TEXT_SIZE:
        if offset in linkage:
            data[offset:offset + 4] = bytes(4)
        else:
            code_targets.add(value)
    else:
        raise SystemExit("relocation at +%#x points outside .data and .text"
                         % offset)

assert len(data_pointers) == 455, "data pointers: %d" % len(data_pointers)
assert len(relocations) - len(data_pointers) == 180, "code pointers"

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_main_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * MAIN's complete 0x2ee00-byte .data image.  The Linkage's code\n")
    output.write(" * pointers and the 455 pointers into .data are zeroed for main.c to\n")
    output.write(" * install; every other code pointer keeps retail's value.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%05x] = %s\n" % (offset, values))

with open(PTR, "w") as output:
    output.write("/* Generated by tools/gen_main_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * MAIN_DATA_POINTER(offset, target): a pointer at image +offset to\n")
    output.write(" * image +target.  MAIN_CODE_TARGET(address): a retail code address\n")
    output.write(" * kept in the image.\n */\n")
    for offset, target in data_pointers:
        output.write("MAIN_DATA_POINTER(0x%05x, 0x%05x)\n" % (offset, target))
    for address in sorted(code_targets):
        output.write("MAIN_CODE_TARGET(0x%08x)\n" % address)

print("wrote %s and %s: %d data pointers, %d code targets" %
      (DST, PTR, len(data_pointers), len(code_targets)))
