#!/usr/bin/env python3
"""Extract normal MDL data and harness boundaries into bin/mdl-diff.

The C callbacks use retail RVAs; these files are ignored derived artifacts.
No retail instructions are emitted as source or used by the C implementation.
"""
import argparse
import json
from pathlib import Path

from mdl_survey import survey
from impscan import PE


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path('orig/Aircraft'))
    parser.add_argument('--output', type=Path, default=Path('bin/mdl-diff'))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    rows = []
    records = []
    for path in sorted(args.root.rglob('*')):
        if not path.is_file() or not path.name.upper().endswith('_N.MDL'):
            continue
        record = survey(path)
        pe = PE(str(path))
        data = record['sections']['.data']
        offset = pe.off(data['rva'])
        payload = pe.b[offset:offset + data['size']]
        if len(payload) != data['size']:
            raise ValueError(f'{path}: truncated .data')
        (args.output / (path.stem + '.data.bin')).write_bytes(payload)
        rows.append('    {%s, 0x%x, 0x%x, 0x%x, 0x%x, %d},' % (
            json.dumps(str(path.resolve())), data['rva'], data['size'],
            pe.exports()['ImportTable'], int(record['update_rva'], 16),
            record['state_size']))
        records.append(record)
    if len(rows) != 8:
        raise ValueError(f'expected eight normal models, found {len(rows)}')
    (args.output / 'fixtures.inc').write_text(
        '/* Generated by tools/gen_mdl_fixtures.py; retail data stays in bin/. */\n'
        + '\n'.join(rows) + '\n')
    (args.output / 'manifest.json').write_text(json.dumps(records, indent=2) + '\n')


if __name__ == '__main__':
    main()
