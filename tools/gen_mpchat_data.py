#!/usr/bin/env python3
"""Extract mpchat.DLL's .data image into C.

MPCHAT keeps ImportTable at +0, its dialog table at +0x30, Linkage at +0x48,
then its strings and all of its state in one 0x50c-byte .data section (0x200
bytes on disk, the rest zero): the window class and control class names, the
chat pane's share of the width (0xc000, 16.16), the instance, the player
lists, the window handles, and at +0x100 the 0x408-byte chat message it sends
through MULTIP.  The reimplementation keeps that layout, because the harness
compares the whole image.  Its relocations are the dialog table's create
routine, the Linkage's two code pointers and Linkage +0x14, which points back
at the dialog table; all four are zeroed here and installed by mpchat.c.

Usage: tools/gen_mpchat_data.py [orig/Modules/mpchat.DLL]
                                [src/mpchat/mpchat_data.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/mpchat.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/mpchat/mpchat_data.inc"

BASE = 0x20840000
DATA_VA = 0x20843000
SIZE = 0x50C
DIALOGS = 0x030
LINKAGE = 0x048

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]
cstr = lambda offset: bytes(data[offset:data.index(0, offset)])

assert [u32(8 * i) for i in range(6)] == [1, 2, 4, 35, 22, 0], "ImportTable"
assert all(u32(8 * i + 4) == 0 for i in range(5)), "import links"
assert [u32(DIALOGS), u32(DIALOGS + 8)] == [0xFF00, 0xC], "dialog table"
assert [u32(DIALOGS + 12 + 4 * i) for i in range(3)] == [0, 0, 0], \
    "dialog table end"
assert u32(LINKAGE) == 0xFFFFFFFF, "module id"
assert [u32(LINKAGE + offset) for offset in (0x0C, 0x10)] == [0, 0], \
    "Linkage header"
assert u32(LINKAGE + 0x14) == DATA_VA + DIALOGS, "Linkage +0x14"
assert cstr(0x60) == b"FS98MPCHAT" and cstr(0x6C) == b"RICHED32.DLL", "names"
assert u32(0x7C) == 0xC000 and u32(0x80) == 0xC000, "split"
assert cstr(0x84) == b" " and cstr(0x88) == b":", "separators"
assert [cstr(o) for o in (0x8C, 0x94, 0x9C, 0xA4)] == \
    [b"Button", b"Edit", b"ListBox", b"RichEdit"], "control classes"
assert cstr(0xB0) == b"\n", "newline"
assert not any(data[0xB4:]), "state is not zero"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size

expected = [DIALOGS + 4, LINKAGE + 4, LINKAGE + 8, LINKAGE + 0x14]
assert sorted(relocations) == expected, "relocation layout changed"

for offset in relocations:
    value = u32(offset)
    assert 0x20841000 <= value < 0x20841c20 or value == DATA_VA + DIALOGS, \
        "relocation points outside .text"
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_mpchat_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * MPCHAT's complete 0x50c-byte .data image, with the dialog table's\n")
    output.write(" * and the Linkage's pointers zeroed for mpchat.c to install.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))

print("wrote", DST)
