#!/usr/bin/env python3
"""Extract MULTIP's initialized data/constants; relocate pointers in C.

No executable bytes are emitted. Code pointers remain zero until the C owner
installs the corresponding callback; all pointer targets are listed separately.
"""
import struct
import sys
from pathlib import Path

source = Path(sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/multip.dll")
directory = Path(sys.argv[2] if len(sys.argv) > 2 else "src/multip")
blob = source.read_bytes()
pe = struct.unpack_from("<I", blob, 0x3c)[0]
optional = pe + 24
base = struct.unpack_from("<I", blob, optional + 28)[0]
assert base == 0x20850000, "reference MULTIP image base moved"
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for index in range(struct.unpack_from("<H", blob, pe + 6)[0]):
    at = section + index * 40
    name = blob[at:at + 8].rstrip(b"\0").decode()
    size, rva, raw_size, raw = struct.unpack_from("<IIII", blob, at + 8)
    sections[name] = (rva, size, raw_size, raw)


def read_rva(rva, size):
    for start, virtual_size, raw_size, raw in sections.values():
        if start <= rva < start + max(virtual_size, raw_size):
            offset = rva - start
            data = blob[raw + offset:raw + min(offset + size, raw_size)]
            return bytearray(data + bytes(size - len(data)))
    raise ValueError(f"unmapped RVA {rva:#x}")


assert sections[".data"][:3] == (0xd000, 0xf38, 0xa00)
assert sections[".text"][:2] == (0x1000, 0xa936)
assert struct.unpack_from("<I", blob, optional + 96)[0] == 0xc1f0
images = {"data": read_rva(0xd000, 0x1000), "rdata": read_rva(0xc000, 0x1f0)}
rva, size = struct.unpack_from("<II", blob, optional + 96 + 5 * 8)
relocations = read_rva(rva, size)
pointers = []
at = 0
while at < len(relocations):
    page, block_size = struct.unpack_from("<II", relocations, at)
    if block_size == 0:
        break
    for offset in range(at + 8, at + block_size, 2):
        entry = struct.unpack_from("<H", relocations, offset)[0]
        if entry >> 12 == 0:
            continue
        assert entry >> 12 == 3
        address = page + (entry & 0xfff)
        owner = "data" if 0xd000 <= address < 0xe000 else "rdata" if 0xc000 <= address < 0xc1f0 else None
        if owner is None:
            continue
        index = address - (0xd000 if owner == "data" else 0xc000)
        target = struct.unpack_from("<I", images[owner], index)[0] - base
        if 0x1000 <= target < 0xb936:
            kind, relative = 1, target - 0x1000
        elif 0xd000 <= target < 0xe000:
            kind, relative = 2, target - 0xd000
        elif 0xc000 <= target < 0xc1f0:
            kind, relative = 3, target - 0xc000
        else:
            raise ValueError(f"unexpected pointer {target + base:#x}")
        pointers.append((owner, index, kind, relative))
        images[owner][index:index + 4] = bytes(4)
    at += block_size

for name, data in images.items():
    with (directory / f"multip_{name}.inc").open("w") as out:
        out.write(f"/* Generated by tools/gen_multip_data.py: .{name}, pointers zeroed. */\n")
        for index in range(0, len(data), 16):
            out.write("    " + "".join(f"0x{value:02x}," for value in data[index:index + 16]) + "\n")
with (directory / "multip_pointers.inc").open("w") as out:
    out.write("/* Generated by tools/gen_multip_data.py: owner, offset, kind, target.\n"
              " * owner: 0=data, 1=rdata; kind: 1=code, 2=data, 3=rdata. */\n")
    for owner, index, kind, target in pointers:
        out.write(f"    {{ {int(owner == 'rdata')}, 0x{index:03x}, {kind}, 0x{target:04x} }},\n")
print(f"MULTIP data: {len(pointers)} pointers, {sum(kind == 1 for _, _, kind, _ in pointers)} code callbacks")

# Static name-label model between functions, not executable instructions.
nametag_size = struct.unpack("<I", read_rva(0x2cf0, 4))[0]
assert nametag_size == 42
nametag = read_rva(0x2cf4, nametag_size)
with (directory / "multip_nametag.inc").open("w") as out:
    out.write("/* Generated by tools/gen_multip_data.py: label model at RVA 0x2cf4. */\n"
              "static const uint8_t s_abyNametag[] = {\n")
    for index in range(0, len(nametag), 16):
        out.write("    " + "".join(f"0x{value:02x}," for value in nametag[index:index + 16]) + "\n")
    out.write("};\n")
