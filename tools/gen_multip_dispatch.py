#!/usr/bin/env python3
"""Extract MULTIP's application dispatcher targets from the retail jump table."""
from pathlib import Path
import re
import struct
import subprocess

root = Path(__file__).resolve().parent.parent
binary = root / 'orig/Modules/multip.dll'
image = binary.read_bytes()
pe = struct.unpack_from('<I', image, 0x3c)[0]
sections, optional_size = struct.unpack_from('<H12xH', image, pe + 6)
optional = pe + 24
base = struct.unpack_from('<I', image, optional + 28)[0]

def offset(address):
    rva = address - base
    for index in range(sections):
        section = optional + optional_size + index * 40
        size, start, raw_size, raw = struct.unpack_from('<4I', image, section + 8)
        if start <= rva < start + max(size, raw_size):
            return raw + rva - start
    raise ValueError(hex(address))

listing = subprocess.check_output(['objdump', '-d', '-Mintel', '--no-show-raw-insn',
    '--start-address=0x20855960', '--stop-address=0x20855c5c', str(binary)], text=True)
lines = {int(address, 16): instruction.strip() for address, instruction in
    re.findall(r'^\s*([0-9a-f]+):\s+(.+)$', listing, re.M)}
source = (root / 'src/multip/multip.c').read_text()
entries = re.findall(r'\(void \*\)(multip_\w+)', source.split('multip_test_entries[] = {')[1].split('};')[0])
rvas = (root / 'tools/difftest/multip_send.inc').read_text().split('s_retail_rvas[] = {')[1].split('};')[0]
names = dict(zip([base + int(value, 16) for value in re.findall(r'0x[0-9a-f]+', rvas)], entries))
rows = []
cases = []
for index, address in enumerate(struct.unpack_from('<32I', image, offset(0x20855c5c))):
    if address == 0x20855c2e:
        assert index == 11
        continue
    calls = [instruction for current, instruction in lines.items() if address <= current < address + 25 and instruction.startswith('call')]
    assert len(calls) == 1, (index, calls)
    target = int(calls[0].split()[1], 16)
    name = names[target]
    assert name == f'multip_handle_{0x1000 + index:x}'
    cases.append(f'    case 0x{0x1000 + index:x}: return {name}(id, packet, size' + (', timestamp' if index == 0x17 else '') + ');\n')
    rows.append(f'        "cmpl $0x{0x1000 + index:x}, %ecx\\n\\tjne {index + 2}f\\n\\t"\n')
    if index == 0x17:
        rows.append('        "movl 28(%esp), %edx\\n\\tpushl %edx\\n\\t"\n')
        rows.append('        "movl 28(%esp), %edx\\n\\tmovl 20(%esp), %ecx\\n\\t"\n')
    else:
        rows.append('        "movl 24(%esp), %edx\\n\\tmovl 16(%esp), %ecx\\n\\t"\n')
    rows.append(f'        "pushl %edx\\n\\tpushl %eax\\n\\tpushl %ecx\\n\\tcall _{name}@{16 if index == 0x17 else 12}\\n\\t"\n')
    rows.append(f'        "addl $12, %esp\\n\\tret $16\\n\\t{index + 2}: "\n')
(root / 'src/multip/multip_dispatch_cases.inc').write_text('/* Generated by tools/gen_multip_dispatch.py from the retail jump table. */\n'
    '#ifdef MULTIP_DISPATCH_C\n' + ''.join(cases) + '#else\n' + ''.join(rows) + '#endif\n')
print('MULTIP dispatch: 31 application targets extracted')
