#!/usr/bin/env python3
"""Extract the ordered profile read/write fields from MULTIP's call sites."""
import re
import subprocess
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent.parent
source = ROOT / "orig/Modules/multip.dll"
blob = source.read_bytes()
listing = subprocess.check_output(["objdump", "-d", "--no-show-raw-insn", "-Mintel", str(source)], text=True)
validators = {
    "MAX_PLAYERS": 1, "MAX_OBSERVERS": 2, "PACKETS_PER_SEC": 3,
    "COLLISION_SECS": 4, "FOLLOWING_MULTIPLIER": 5,
    "MAX_TRACK_NAME_DISPLAY_TIME": 6, "MAX_SEGMENT_SIZE": 7,
    "MAX_SEGMENTS_PER_SEC": 8, "SESSION_LIST_UPDATE_TIME": 9,
    "PLAYER_LIST_UPDATE_TIME": 10, "TIME_BETWEEN_CONNECTION_ATTEMPTS": 11,
}
fields = {"load": [], "save": []}
pushes = []
registers = {}
for line in listing.splitlines():
    match = re.match(r"\s*([0-9a-f]+):\s+(\S+)\s*(.*)", line)
    if not match:
        continue
    address = int(match[1], 16)
    mode = "load" if 0x20859f30 <= address < 0x2085a3d2 else "save" if 0x2085a3e0 <= address < 0x2085a6a4 else None
    if mode is None:
        continue
    instruction, operands = match[2], match[3]
    load = re.fullmatch(r"(e[a-z]{2}),(?:DWORD PTR )?ds:0x(2085[0-9a-f]{4})", operands)
    if instruction == "mov" and load:
        registers[load[1]] = int(load[2], 16)
    if instruction == "push":
        pushes.append(int(operands, 16) if operands.startswith("0x") else registers.get(operands))
    if instruction != "call":
        continue
    slot = re.search(r"\+0x(a8|ac|c8|cc)\]", operands)
    assert slot, (hex(address), operands)
    slot = int(slot[1], 16)
    length = pushes[-4] if slot == 0xc8 else 0
    if mode == "load":
        section, key, value = pushes[-1], pushes[-2], pushes[-3]
    else:
        section, key, value = pushes[-1], pushes[-2], pushes[-3]
    assert section == 0x2085d198 and 0x2085d000 <= key < 0x2085da00
    key_offset = key - 0x2085d000
    text_at = 0xb200 + key_offset
    name = blob[text_at:blob.index(b"\0", text_at)].decode()
    assert value is not None and 0x2085d000 <= value < 0x2085e000, (name, value)
    fields[mode].append((key_offset, value - 0x2085d000, length if slot == 0xc8 else int(slot == 0xcc), validators.get(name, 0), name))
    pushes.clear()
with (ROOT / "src/multip/multip_profile_fields.inc").open("w") as out:
    out.write("/* Generated by tools/gen_multip_profile.py; ordered retail profile fields. */\n")
    for mode, rows in fields.items():
        out.write(f"static const struct multip_profile_field s_profile_{mode}_fields[] = {{\n")
        for key, value, length, validator, name in rows:
            out.write(f"    {{ 0x{key:03x}, 0x{value:03x}, {length}, {validator} }}, /* {name} */\n")
        out.write("};\n")
print({mode: len(rows) for mode, rows in fields.items()})
