#!/usr/bin/env python3
"""Extract MULTIP's ordered weather-message copy fields from retail calls."""
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parent.parent
listing = subprocess.check_output([
    "objdump", "-d", "-Mintel", "--no-show-raw-insn",
    "--start-address=0x20857140", "--stop-address=0x208576c4",
    str(root / "orig/Modules/multip.dll"),
], text=True)
fields = re.findall(
    r"add\s+eax,0x([0-9a-f]+)\s*\n[^\n]*push\s+0x([0-9a-f]+)\s*\n"
    r"[^\n]*lea\s+ecx,\[esp\+0x([0-9a-f]+)\]", listing)
assert len(fields) == 28
end = 8
rows = []
for source, size, dest in fields:
    source, size, dest = int(source, 16), int(size, 16), int(dest, 16) - 4
    assert dest == end
    end += size
    rows.append(f"    {{0x{source:03x}, 0x{dest:03x}, 0x{size:02x}}},\n")
assert end == 0x258  # Retail sends another four caller-stack bytes after this.
# Independently decode the receive-side copies before sharing this table.
receive = subprocess.check_output([
    "objdump", "-d", "-Mintel", "--no-show-raw-insn",
    "--start-address=0x20852270", "--stop-address=0x2085274a",
    str(root / "orig/Modules/multip.dll"),
], text=True)
registers = {}
pushes = []
received = []
for line in receive.splitlines():
    match = re.match(r"\s*[0-9a-f]+:\s+(\S+)\s*(.*)", line)
    if not match:
        continue
    instruction, operands = match.groups()
    if instruction == "mov":
        dest, source = operands.split(",", 1)
        if source == "DWORD PTR [esp+0x8]": registers[dest] = ("packet", 0)
        elif source.endswith("ds:0x2085d00c"): registers[dest] = ("global", 0)
        else: registers[dest] = None
    elif instruction == "lea":
        dest, source = operands.split(",", 1)
        address = re.fullmatch(r"\[(e[a-z]{2})\+0x([0-9a-f]+)\]", source)
        base = registers.get(address[1]) if address else None
        registers[dest] = (base[0], base[1] + int(address[2], 16)) if base else None
    elif instruction == "add":
        dest, source = operands.split(",", 1)
        base = registers.get(dest)
        registers[dest] = (base[0], base[1] + int(source, 16)) if base and source.startswith("0x") else None
    elif instruction == "push":
        pushes.append(int(operands, 16) if operands.startswith("0x") else registers.get(operands))
    elif instruction == "call":
        if "+0x21c]" in operands:
            size, source, dest = pushes[-3:]
            assert source[0] == "packet" and dest[0] == "global"
            received.append((dest[1], source[1], size))
        pushes.clear()
        for register in ("eax", "ecx", "edx"): registers[register] = None
assert received == [(int(a, 16), int(c, 16) - 4, int(b, 16)) for a, b, c in fields]
print("MULTIP weather: receive copy order independently matches send table")

(root / "src/multip/multip_weather_fields.inc").write_text(
    "/* Generated by tools/gen_multip_weather.py: source, destination, size. */\n"
    "static const struct multip_weather_field s_weather_fields[] = {\n" + "".join(rows) + "};\n")
print(f"MULTIP weather: {len(rows)} ordered copy fields")

