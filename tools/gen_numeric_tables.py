#!/usr/bin/env python3
"""Extract NUMERIC.DLL's initial .data image and .rdata constants into C.

NUMERIC keeps its constants and its state side by side in .data -- the
powers of ten its digit printers divide by, the degree/minute/second division
tables, the sprintf formats, and the settings init reads from FLTSIM98.CFG --
so the reimplementation keeps one buffer laid out exactly as retail's, and
addresses it by the same offsets a disassembly listing shows.  Only the
initialised part is on disk; the rest of the section (up to 0x400 here) is
zero, as the loader leaves it.

Usage: tools/gen_numeric_tables.py [orig/Modules/NUMERIC.DLL] [src/numeric/numeric_data.inc]
"""
import struct, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'orig/Modules/NUMERIC.DLL'
DST = sys.argv[2] if len(sys.argv) > 2 else 'src/numeric/numeric_data.inc'

b = open(SRC, 'rb').read()
e = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, e + 6)[0]
so = e + 24 + struct.unpack_from('<H', b, e + 20)[0]
secs = {}
for _ in range(nsec):
    name = b[so:so + 8].rstrip(b'\0').decode()
    vsz, va, rsz, ro = struct.unpack_from('<IIII', b, so + 8)
    secs[name] = (va, vsz, rsz, ro)
    so += 40

va, vsz, rsz, ro = secs['.data']
data = b[ro:ro + min(rsz, vsz)]
assert data[0x130:0x134] == struct.pack('<I', 100000000), '.data does not start the power-of-ten table at +0x130'
assert data[0x64:0x6e] == b"%d* %2.4f'", 'format strings not where expected'

va, vsz, rsz, ro = secs['.rdata']
rdata = b[ro:ro + min(rsz, vsz)]
dbl = [struct.unpack_from('<d', rdata, o)[0] for o in range(0x10, 0x48, 8)]
assert dbl[1] == 60.0 and dbl[4] == 180.0 and dbl[5] == 360.0 and dbl[6] == 10.0

def arr(name, blob, size):
    out = ['static uint8_t %s[0x%x] = {' % (name, size)]
    for i in range(0, len(blob), 16):
        out.append('    ' + ' '.join('0x%02x,' % c for c in blob[i:i + 16]))
    out.append('};')
    return '\n'.join(out)

with open(DST, 'w') as f:
    f.write('/* Generated by tools/gen_numeric_tables.py from %s -- do not edit.\n' % SRC)
    f.write(' *\n'
            ' * fs98_numeric_data: NUMERIC\'s .data as the loader maps it -- the 0x%x\n'
            ' * initialised bytes from the file, then zeroes to 0x400.  Mutable: init and\n'
            ' * the latitude/longitude printers keep their state in it, at the offsets\n'
            ' * retail uses.\n'
            ' *\n'
            ' * fs98_numeric_rdata: .rdata+0x10 to +0x48, seven doubles, bit-exact.\n'
            ' */\n' % len(data))
    f.write(arr('fs98_numeric_data', data, 0x400) + '\n\n')
    f.write('static const uint64_t fs98_numeric_rdata[7] = {\n')
    for o, v in zip(range(0x10, 0x48, 8), dbl):
        f.write('    0x%016xull,   /* .rdata+0x%02x  %r */\n' % (struct.unpack_from('<Q', rdata, o)[0], o, v))
    f.write('};\n')
