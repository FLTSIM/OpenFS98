#!/usr/bin/env python3
"""Extract Options' vtable and message-map bindings and build-only Windows resources.

    python3 -B tools/gen_options_runtime.py

As tools/gen_flights_runtime.py does for Flights. No machine code or resource payload is
written to tracked source: the include holds ABI metadata (import names, which vtable slot is
which import or which of our functions, the message maps, the registrations); the .res and
the SIMSUI ordinal anchor go under bin/.

Which of our functions a retail routine is comes from the differential harness's operation
table (tools/difftest/optionseventsdiff.c), which pairs every routine it tests with ours, so
the two cannot drift apart: a routine the harness does not test cannot be bound here.
"""
from pathlib import Path
import re
import struct

from dialogmap import Fs98Pe, SurveyError

BASE = 0x22390000
IMAGE = 'orig/English/Options.DLL'
HARNESS = 'tools/difftest/optionseventsdiff.c'
TABLES = 'tools/gen_options_tables.py'
# A dialog's vtable has CSimsDialog's 60 slots; a tab page's CSimsTabPage's 61 (+0xf0, the page's
# init). After the last slot comes the next class's vtable or a message map, never called.
DIALOG_SLOTS, PAGE_SLOTS = 60, 61
OPERATION = re.compile(r'\b(?:SHARED|VIDEO_FINISHED|VIDEO_MESSAGE|SAVE_VIDEO|FLIGHT_VIDEO|ADD_LOGBOOK|'
                       r'LOGBOOK_ENTRY|BOOK|LANDING|MANOEUVRE|ANALYSIS|REPLAY|DEMO|DISPLAY)\(0x([0-9a-f]+), (\w+)')
CLASS_ROW = re.compile(r'CLASS\(0x([0-9a-f]+), 0x([0-9a-f]+), 0x([0-9a-f]+), (\w+),')
NUMBER = r"((?:0x)?[0-9a-f]+)"
TABLE_ROW = re.compile(r"\('(\w+)'" + (", " + NUMBER) * 8 + ",")


def resource_name(name):
    if isinstance(name, int):
        if name > 0xffff:
            raise SurveyError('resource ordinal exceeds WORD')
        return struct.pack('<HH', 0xffff, name)
    return name.encode('utf-16-le') + b'\0\0'


def thunk_slot(pe, rva):
    """The import slot a `jmp [slot]` thunk goes through, or None."""
    offset = pe.file_offset(rva, 6)
    if pe.read_bytes(offset, 2) != b'\xff\x25':
        return None
    return pe.read_uint32(offset + 2)


def through_jumps(pe, rva):
    """A routine that is only a jump (e9 rel32, or eb rel8) to another: the other."""
    for _ in range(4):
        offset = pe.file_offset(rva, 5)
        opcode = pe.read_bytes(offset, 1)[0]
        if opcode == 0xe9:
            rva = (rva + 5 + int.from_bytes(pe.read_bytes(offset + 1, 4), 'little', signed=True)) & 0xffffffff
        elif opcode == 0xeb:
            rva = rva + 2 + int.from_bytes(pe.read_bytes(offset + 1, 1), 'little', signed=True)
        else:
            break
    return rva


def classes():
    """(name, vtable RVA, page, factory RVA) in gen_options_tables.py's order"""
    rows = []
    for row in TABLE_ROW.findall(Path(TABLES).read_text()):
        name, descriptor, factory, vtable = row[0], int(row[3], 0), int(row[7], 0), int(row[8], 0)
        rows.append((name, vtable, factory == 0 and descriptor == 0, factory, int(row[6], 0)))
    return rows


def local_functions(rows):
    """retail RVA -> our function, from the harness's operations and the class table"""
    text = Path(HARNESS).read_text()
    local = {}
    for rva, name in OPERATION.findall(text):
        local[int(rva, 16)] = 'fs98_options_' + name
    for help_rva, context, exchange, name in CLASS_ROW.findall(text):
        local[int(help_rva, 16)] = f'fs98_options_{name}_help'
        local[int(context, 16)] = f'fs98_options_{name}_context'
        local[int(exchange, 16)] = f'fs98_options_{name}_exchange'
    for name, _, _, _, delete in rows:
        local[delete] = f'fs98_options_{name}_delete'
    local[0x4290] = 'fs98_options_notify_delete'
    local[0x8380] = 'fs98_options_book_list_delete'
    return local


def main():
    pe = Fs98Pe(IMAGE)
    if pe.uiBase != BASE or pe.linkage()['id'] != 0x80000007:
        raise SurveyError('expected the reference Options image at 0x22390000')
    directory = Path('bin/options-diff')
    directory.mkdir(parents=True, exist_ok=True)
    rows = classes()
    local = local_functions(rows)
    imports = [binding for binding in pe.imports() if binding['dll'].upper() in ('SIMSUI.DLL', 'MFC42.DLL')]
    import_indices = {binding['iat_va']: index for index, binding in enumerate(imports)}
    lines = ['/* Generated by tools/gen_options_runtime.py; ABI metadata only. */',
             'static const struct options_import_binding s_import_bindings[] = {']
    for binding in imports:
        name = binding['name']
        ordinal = int(name[1:]) if name.startswith('#') else 0
        lines.append(f'    {{"{binding["dll"]}", "{name}", {ordinal}, 0x{binding["iat_va"] - BASE:x}}},')
    lines += ['};', 'static const struct options_virtual_binding s_virtual_bindings[] = {']
    maps = {}
    for table, (name, vtable, page, _, _) in enumerate(rows):
        slots = PAGE_SLOTS if page else DIALOG_SLOTS
        for slot in range(slots):
            function_rva = pe.va_uint32(BASE + vtable + slot * 4) - BASE
            if slot == 12:          # GetMessageMap: the generated getter
                lines.append(f'    {{{table}, {slot}, -1, (void *)options_map_getters[{table}]}},')
                getter = function_rva
                offset = pe.file_offset(getter, 6)
                if pe.read_bytes(offset, 1) != b'\xb8' or pe.read_bytes(offset + 5, 1) != b'\xc3':
                    raise SurveyError(f'{name}: message map getter moved')
                maps[table] = pe.read_uint32(offset + 1)
                continue
            if function_rva in local:
                lines.append(f'    {{{table}, {slot}, -1, (void *){local[function_rva]}}},')
                continue
            iat = thunk_slot(pe, function_rva)
            if iat not in import_indices:
                raise SurveyError(f'{name} +{slot * 4:#x}: unbound vtable target {function_rva:#x}')
            lines.append(f'    {{{table}, {slot}, {import_indices[iat]}, 0}},')
    lines.append('};')
    page_bases = set()
    for table, (name, _, page, _, _) in enumerate(rows):
        message_map = maps[table]
        lines.append(f'static const struct options_message_entry s_{name}_messages[] = {{')
        entries = pe.va_uint32(message_map + 4)
        for index in range(64):
            fields = [pe.va_uint32(entries + index * 24 + field * 4) for field in range(6)]
            if not any(fields):
                lines.append('    {0, 0, 0, 0, 0, 0}')
                break
            if fields[5] == 0:
                # page 0x386's first entry, WM_ACTIVATE to CSimsTabPage::OnActivate, is filled in
                # at run time by a static initialiser (0x22392cc0): an import
                lines.append(f'    {{0x{fields[0]:x}, 0x{fields[1]:x}, 0x{fields[2]:x}, 0x{fields[3]:x}, 0x28, '
                             f'OPTIONS_ON_ACTIVATE}},')
                continue
            handler = fields[5] - BASE
            if handler not in local:
                handler = through_jumps(pe, handler)
            if handler not in local:
                raise SurveyError(f'{name}: unbound message handler {handler:#x}')
            literals = ', '.join(f'0x{value:x}' for value in fields[:5])
            lines.append(f'    {{{literals}, (void *){local[handler]}}},')
        else:
            raise SurveyError(f'{name}: unterminated message map')
        lines.append('};')
    # Options' own non-dialog classes: its CNotify (0x16ab0) and the Logbook's rows list
    # (0x17bb0), each slot an import or ours, up to the first word that is not code
    for name, vtable in (('notify', 0x16ab0), ('book_list', 0x17bb0)):
        lines.append(f'static const struct options_virtual_binding s_{name}_bindings[] = {{')
        slot = 0
        while slot < 128:
            word = pe.va_uint32(BASE + vtable + slot * 4)
            if not pe.is_code(word):
                break
            function_rva = word - BASE
            if name == 'book_list' and slot == 12:
                # its own message map (WM_HSCROLL to the Logbook's scroll handler) over
                # CSimsListBox's: the runtime's getter, the entries below
                lines.append(f'    {{0, {slot}, -1, (void *)options_book_list_map}},')
            elif function_rva in local:
                lines.append(f'    {{0, {slot}, -1, (void *){local[function_rva]}}},')
            else:
                iat = thunk_slot(pe, function_rva)
                if iat not in import_indices:
                    break           # the next class's code: this vtable has ended
                lines.append(f'    {{0, {slot}, {import_indices[iat]}, 0}},')
            slot += 1
        lines += ['    {-1, 0, 0, 0}', '};', f'#define {name.upper()}_SLOTS {slot}']
    getter = pe.va_uint32(BASE + 0x17bb0 + 0x30) - BASE
    message_map = pe.read_uint32(pe.file_offset(getter, 6) + 1)
    entries = pe.va_uint32(message_map + 4)
    lines.append('static const struct options_message_entry s_book_list_messages[] = {')
    for index in range(16):
        fields = [pe.va_uint32(entries + index * 24 + field * 4) for field in range(6)]
        if not any(fields):
            lines.append('    {0, 0, 0, 0, 0, 0}')
            break
        handler = through_jumps(pe, fields[5] - BASE)
        if handler not in local:
            raise SurveyError(f'book list: unbound message handler {handler:#x}')
        lines.append('    {' + ', '.join(f'0x{value:x}' for value in fields[:5]) + f', (void *){local[handler]}}},')
    lines.append('};')
    lines.append('static const struct options_message_entry *const s_messages[] = {')
    lines += [f'    s_{name}_messages,' for name, _, _, _, _ in rows] + ['};']
    lines.append('static const uint8_t s_pages[] = {' + ', '.join(str(int(page)) for _, _, page, _, _ in rows) + '};')
    lines.append('static const struct options_dialog s_dialogs[] = {')
    factories = {factory: name for name, _, _, factory, _ in rows if factory}
    for dialog in pe.linkage()['dialogs']:
        lines.append(f'    {{0x{dialog["id"]:x}, fs98_options_{factories[dialog["create_va"] - BASE]}_create, {dialog["flags"]}}},')
    lines += ['    {0, 0, 0}', '};', f'#define CLASS_TOTAL {len(rows)}', '']
    Path('src/options/options_runtime_tables.inc').write_text('\n'.join(lines))

    # A PE import by ordinal makes the loader resolve SIMSUI and its MFC before our DllMain.
    ui = Fs98Pe('orig/SIMSUI.DLL')
    export = ui.file_offset(ui.directory(0)[0], 40)
    base = ui.read_uint32(export + 16)
    names_rva = ui.read_uint32(export + 32)
    ordinals_rva = ui.read_uint32(export + 36)
    anchor_ordinal = None
    for index in range(ui.read_uint32(export + 24)):
        name_rva = ui.read_uint32(ui.file_offset(names_rva + index * 4, 4))
        if ui.c_string(name_rva) == '?ui_new@@YAPAXI@Z':
            anchor_ordinal = base + ui.read_uint16(ui.file_offset(ordinals_rva + index * 2, 2))
    if anchor_ordinal is None:
        raise SurveyError('SIMSUI ui_new export missing')
    (directory / 'simsui-anchor.def').write_text(
        f'LIBRARY SIMSUI.DLL\nEXPORTS\n    fs98_options_simsui_anchor @{anchor_ordinal} NONAME\n')

    resources = bytearray(struct.pack('<IIHHHHIHHII', 0, 32, 0xffff, 0, 0xffff, 0, 0, 0, 0, 0, 0))
    for resource in pe.resources():
        if resource['type'] == 16:
            continue  # Do not copy the retail company's version resource.
        resource_names = resource_name(resource['type']) + resource_name(resource['id'])
        resource_names += b'\0' * (-len(resource_names) % 4)
        header = struct.pack('<II', resource['size'], 8 + len(resource_names) + 16)
        header += resource_names + struct.pack('<IHHII', 0, 0x1030, resource['language'], 0, 0)
        resources += header
        resources += pe.read_bytes(pe.file_offset(resource['rva'], resource['size']), resource['size'])
        resources += b'\0' * (-len(resources) % 4)
    (directory / 'options.res').write_bytes(resources)


if __name__ == '__main__':
    main()
