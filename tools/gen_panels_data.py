#!/usr/bin/env python3
"""Extract PANELS.DLL's .data image and its .rdata constants into C.

PANELS keeps one .data section of 0x16580 bytes, 0x1e00 of them
initialised: ImportTable at +0x0, Linkage at +0x50, the strings, and from
+0x610 the gauge variables' table, records of 16 bytes (a function, a
pointer to the GLOBAL import link, an offset into GLOBAL, a size).  The
rest is buffers.  The reimplementation keeps that layout so the harness can
compare the whole image.  Its relocations are code pointers (the Linkage
and the table's functions) and pointers to the GLOBAL link at +0xc: both
are zeroed here and listed for panels.c to install.

.rdata (0x1fb bytes) is the doubles and float constants.

Usage: tools/gen_panels_data.py [orig/Modules/PANELS.DLL]
                                [src/panels/panels_data.inc]
                                [src/panels/panels_rdata.inc]
                                [src/panels/panels_pointers.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/PANELS.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/panels/panels_data.inc"
RDS = sys.argv[3] if len(sys.argv) > 3 else "src/panels/panels_rdata.inc"
PTR = sys.argv[4] if len(sys.argv) > 4 else "src/panels/panels_pointers.inc"

BASE = 0x10000000
TEXT_VA = 0x10001000
TEXT_SIZE = 0xc376
RDATA_VA = 0x1000e000
RDATA_SIZE = 0x1fb
DATA_VA = 0x1000f000
SIZE = 0x16580
INITIALISED = 0x1e00
LINKAGE = 0x50
GLOBAL_LINK = 0x0c

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40
assert image_base == BASE, "image base moved"


def read(name, va, size):
    rva, vsize, raw_size, raw = sections[name]
    start = va - BASE - rva
    out = bytearray(blob[raw + start:raw + min(raw_size, start + size)])
    out.extend(bytes(size - len(out)))
    return out


rva, vsize, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and vsize == SIZE and raw_size == INITIALISED, \
    ".data moved or resized"
rva, vsize, raw_size, raw = sections[".text"]
assert BASE + rva == TEXT_VA and vsize == TEXT_SIZE, ".text moved or resized"
rva, vsize, raw_size, raw = sections[".rdata"]
assert BASE + rva == RDATA_VA and vsize == RDATA_SIZE, ".rdata moved or resized"

data = read(".data", DATA_VA, INITIALISED)
rdata = read(".rdata", RDATA_VA, RDATA_SIZE)
u32 = lambda b, o: struct.unpack_from("<I", b, o)[0]

assert [u32(data, 8 * i) for i in range(10)] == \
    [1, 2, 23, 4, 13, 19, 3, 39, 10, 0], "ImportTable"
assert u32(data, LINKAGE) == 15, "module id"

# relocations
rva, size = struct.unpack_from("<II", blob, optional + 96 + 5 * 8)
rrva, rvsize, rraw_size, rraw = sections[".reloc"]
at, end, relocs = rraw + rva - rrva, rraw + rva - rrva + size, []
while at < end:
    page, block = struct.unpack_from("<II", blob, at)
    if block == 0:
        break
    for i in range((block - 8) // 2):
        w = struct.unpack_from("<H", blob, at + 8 + 2 * i)[0]
        if w >> 12 == 3:
            relocs.append(BASE + page + (w & 0xFFF))
    at += block

assert not [r for r in relocs if RDATA_VA <= r < RDATA_VA + RDATA_SIZE], ".rdata pointers"
code, link = [], []
for r in relocs:
    if not DATA_VA <= r < DATA_VA + SIZE:
        continue
    o, v = r - DATA_VA, u32(data, r - DATA_VA)
    if TEXT_VA <= v < TEXT_VA + TEXT_SIZE:
        code.append((o, v - TEXT_VA))
    elif v == DATA_VA + GLOBAL_LINK:
        link.append(o)
    else:
        raise SystemExit("unexpected relocation at .data+%#x" % o)
    data[o:o + 4] = bytes(4)
assert len(code) == 83 and len(link) == 311, "pointers"


def write_bytes(path, b, what):
    with open(path, "w") as f:
        f.write("/* %s -- generated by tools/gen_panels_data.py from "
                "PANELS.DLL; do not edit. */\n" % what)
        for i in range(0, len(b), 16):
            f.write("    " + "".join("0x%02x," % c for c in b[i:i + 16]) + "\n")


write_bytes(DST, data, ".data+0..+0x%x (the rest is zero), pointers zeroed" % INITIALISED)
write_bytes(RDS, rdata, ".rdata, 0x%x bytes" % RDATA_SIZE)
with open(PTR, "w") as f:
    f.write("/* .data's pointers -- generated by tools/gen_panels_data.py; do not edit.\n"
            " * C(.data offset, .text offset): code; L(.data offset): the GLOBAL link. */\n")
    for o, t in code:
        f.write("    C(0x%04x, 0x%04x)\n" % (o, t))
    for o in link:
        f.write("    L(0x%04x)\n" % o)
