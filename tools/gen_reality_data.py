#!/usr/bin/env python3
"""Extract REALITY.DLL's .data image and its .rdata into C.

REALITY keeps one 0x510-byte .data section (0x400 bytes on disk, the rest
zero): a jump table, its state, ImportTable at +0x48, Linkage at +0xb0, the
windscreen's crack, the crash-analysis dialog's block and exchange table, two
host arrays, the graph's labels and the graph window's record.  The
reimplementation keeps that layout so the harness can compare the whole
image.  Its relocations are fifteen code pointers (zeroed here and installed
by reality.c) and four pointers into the image itself (likewise).

The graph's scale search reads .rdata's tables with no bound, so the second
file carries .rdata whole, as the file has it: the search stops inside it for
any range below 2,545,942,528.

Usage: tools/gen_reality_data.py [orig/Modules/REALITY.DLL]
                                 [src/reality/reality_data.inc]
                                 [src/reality/reality_rdata.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/REALITY.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/reality/reality_data.inc"
RDS = sys.argv[3] if len(sys.argv) > 3 else "src/reality/reality_rdata.inc"

BASE = 0x208B0000
DATA_VA = 0x208B4000
RDATA_VA = 0x208B3000
SIZE = 0x510
IMPORTS = 0x048
LINKAGE = 0x0B0

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * i) for i in range(13)] == \
    [1, 2, 4, 16, 7, 13, 3, 17, 39, 20, 10, 22, 0], "ImportTable"
assert u32(LINKAGE) == 32, "module id"
assert u32(0x28) == 0x78 and u32(0x30) == 0x80000000, "state defaults"
assert u32(0x208) == 0xFFFFFFFF, "the crack's end"
assert data[0x218] == 0x2D, "the descent's sign"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size

CODE = [4 * i for i in range(8)] + [LINKAGE + 4, LINKAGE + 8, LINKAGE + 0x18,
                                    LINKAGE + 0x1C, 0x22C, 0x230, 0x2A0]
SELF = {0x23C: 0x218, 0x240: 0x428, 0x248: 0x300, 0x250: 0x3F8}
assert sorted(relocations) == sorted(CODE + list(SELF)), "relocation layout changed"

for offset in CODE:
    assert 0x208B1000 <= u32(offset) < 0x208B22D6, "relocation points outside .text"
    data[offset:offset + 4] = bytes(4)
for offset, target in SELF.items():
    assert u32(offset) == DATA_VA + target, "self pointer moved"
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_reality_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * REALITY's complete 0x510-byte .data image, with its code pointers\n")
    output.write(" * and pointers into itself zeroed for reality.c to install.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))

rva, virtual_size, raw_size, raw = sections[".rdata"]
assert BASE + rva == RDATA_VA, ".rdata moved"
rdata = blob[raw:raw + virtual_size]
assert struct.unpack_from("<II", rdata, 0x58) == (65535, 10000), "feet table"
assert struct.unpack_from("<d", rdata, 0xC0)[0] == 0.30480017489753664, "constants"

with open(RDS, "w") as output:
    output.write("/* Generated by tools/gen_reality_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * REALITY's .rdata, 0x%x bytes: the graph's scale tables and\n" % len(rdata))
    output.write(" * constants, then the export directory the scale search can read on into.\n */\n")
    for offset in range(0, len(rdata), 16):
        chunk = rdata[offset:offset + 16]
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%03x] = %s\n" % (offset, values))

print("wrote", DST, "and", RDS)
