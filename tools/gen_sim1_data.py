#!/usr/bin/env python3
"""Verify the CD SIM1 and extract data only into ignored harness output."""
import hashlib
import json
from pathlib import Path
import struct

from impscan import PE

ROOT = Path(__file__).resolve().parents[1]
SHA256 = "66ebc70ff63fd6beb51a146b9fa2d1ce5d92a5cdff99af92960eed9e2ab68c1b"


def main():
    source = ROOT / "cd/fs98/Sim/SIM1.sim"
    content = source.read_bytes()
    if hashlib.sha256(content).hexdigest() != SHA256:
        raise SystemExit("SIM1 reference CD hash differs")
    original = ROOT / "orig/Sim/SIM1.sim"
    if original.exists() and original.read_bytes() != content:
        raise SystemExit("existing orig/Sim/SIM1.sim differs; refusing to overwrite")
    original.parent.mkdir(parents=True, exist_ok=True)
    if not original.exists():
        original.write_bytes(content)
    pe = PE(str(original))
    exports = pe.exports()
    if pe.base != 0x22000000 or exports != {"ImportTable": 0x16000, "Linkage": 0x16058}:
        raise SystemExit("SIM1 export layout differs")
    data_section = next(section for section in pe.secs if section[1] == 0x16000)
    size, rva, raw_size, raw_offset = data_section
    if (size, raw_size) != (0x43f8, 0x1200):
        raise SystemExit("SIM1 data extent differs")
    data = content[raw_offset:raw_offset + raw_size] + bytes(size - raw_size)
    imports = [struct.unpack_from("<II", data, offset) for offset in range(0, 0x58, 8)]
    if imports != [(i, 0) for i in (1, 2, 23, 4, 16, 3, 32, 39, 20, 10, 0)]:
        raise SystemExit("SIM1 imports differ")
    linkage = list(struct.unpack_from("<15I", data, 0x58))
    expected = [25, 0x22001060, 0x220010a0, 0, 0, 0, 0x2200ac0d,
                0x2200fc40, 0x22017150, 0x22017158, 0x2200ac2f,
                0x220117c0, 0x220117e0, 0x22011750, 0x220096b8]
    if linkage != expected:
        raise SystemExit("SIM1 Linkage differs")
    if struct.unpack_from("<Q", content, pe.off(0x152e8))[0] != 0:
        raise SystemExit("SIM1 zero constant differs")
    if struct.unpack_from("<Q", content, pe.off(0x152f0))[0] != 0x3f00000000000000:
        raise SystemExit("SIM1 integer scale differs")
    output = ROOT / "bin/sim1-diff"
    output.mkdir(parents=True, exist_ok=True)
    with (output / "sim1_data.inc").open("w") as stream:
        stream.write("/* Generated by tools/gen_sim1_data.py; data only. */\n")
        for offset in range(0x94, raw_size, 16):
            stream.write("    " + ", ".join(f"0x{value:02x}" for value in data[offset:offset + 16]) + ",\n")
    (output / "survey.json").write_text(json.dumps({
        "source": str(source.relative_to(ROOT)), "sha256": SHA256,
        "base": pe.base, "exports": exports, "imports": imports,
        "linkage": linkage, "data_rva": rva, "data_size": size,
        "data_raw_size": raw_size, "sections": pe.secs,
    }, indent=2) + "\n")
    print("SIM1 reference verified; data and survey in bin/sim1-diff")


if __name__ == "__main__":
    main()
