#!/usr/bin/env python3
"""The native SIM1's data from the CD's SIM1.sim, into bin/sim1-native (not in the repo):

  sim1_rdata.inc  retail's .rdata (0x22015000, 0x759 bytes): the constants RF64 reads
  sim1_data.inc   retail's .data from +0x94 (past the ImportTable and Linkage, which
                  src/sim1/sim1_native.c writes itself) to the end of its raw bytes
  sim1.res        retail's resources, for windres

Retail's relocations are checked: the only pointers in .data are the Linkage's, and none are
in .rdata, so the bytes can be taken as they are."""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from impscan import PE  # noqa: E402


def relocations(content, pe):
    header = struct.unpack_from('<I', content, 0x3c)[0]
    rva, size = struct.unpack_from('<II', content, header + 24 + 96 + 5 * 8)
    offset, end, sites = pe.off(rva), pe.off(rva) + size, []
    while offset < end:
        page, block = struct.unpack_from('<II', content, offset)
        for at in range((block - 8) // 2):
            entry = struct.unpack_from('<H', content, offset + 8 + 2 * at)[0]
            if entry >> 12 == 3:
                sites.append(page + (entry & 0xfff))
        offset += block
    return sites


def resources(content, pe):
    """The .rsrc tree (type/id/language, all numeric) as a .res file."""
    rsrc = next(section for section in pe.secs if section[1] == 0x1c000)
    base = rsrc[3]

    def entries(offset):
        named, numbered = struct.unpack_from('<HH', content, base + offset + 12)
        for at in range(named + numbered):
            name, target = struct.unpack_from('<II', content, base + offset + 16 + 8 * at)
            if name & 0x80000000:
                raise SystemExit('a named SIM1 resource')
            yield name, target

    out = bytearray(struct.pack('<IIHHHHIHHII', 0, 32, 0xffff, 0, 0xffff, 0, 0, 0, 0, 0, 0))
    for kind, kinds in entries(0):
        for ident, idents in entries(kinds & 0x7fffffff):
            for language, leaf in entries(idents & 0x7fffffff):
                data_rva, size = struct.unpack_from('<II', content, base + leaf)
                out += struct.pack('<IIHHHHIHHII', size, 32, 0xffff, kind, 0xffff, ident, 0, 0x1030, language, 0, 0)
                out += content[pe.off(data_rva):pe.off(data_rva) + size]
                out += bytes(-len(out) % 4)
    return bytes(out)


def table(data):
    return ''.join('    ' + ', '.join(f'0x{value:02x}' for value in data[at:at + 16]) + ',\n'
                   for at in range(0, len(data), 16))


def main():
    path = ROOT / 'orig/Sim/SIM1.sim'
    content = path.read_bytes()
    pe = PE(str(path))
    if pe.base != 0x22000000:
        raise SystemExit('image base moved (docs/building.md, "Which CD")')
    sections = {section[1]: section for section in pe.secs}
    rdata, data = sections[0x15000], sections[0x16000]
    if (rdata[0], data[0], data[2]) != (0x759, 0x43f8, 0x1200):
        raise SystemExit('SIM1 section layout differs')
    sites = relocations(content, pe)
    in_data = sorted(site - 0x16000 for site in sites if 0x16000 <= site < 0x16000 + data[0])
    if in_data != [0x5c, 0x60, 0x70, 0x74, 0x78, 0x7c, 0x80, 0x84, 0x88, 0x8c, 0x90]:
        raise SystemExit('SIM1 .data holds pointers besides the Linkage')
    if any(0x15000 <= site < 0x15000 + rdata[0] for site in sites):
        raise SystemExit('SIM1 .rdata holds pointers')
    out = ROOT / 'bin/sim1-native'
    out.mkdir(parents=True, exist_ok=True)
    head = '/* Generated by tools/gen_sim1_native.py from the CD\'s SIM1.sim; data only. */\n'
    (out / 'sim1_rdata.inc').write_text(head + table(content[rdata[3]:rdata[3] + rdata[0]]))
    (out / 'sim1_data.inc').write_text(head + table(content[data[3] + 0x94:data[3] + data[2]]))
    (out / 'sim1.res').write_bytes(resources(content, pe))
    print('SIM1 native data in bin/sim1-native')


if __name__ == '__main__':
    main()
