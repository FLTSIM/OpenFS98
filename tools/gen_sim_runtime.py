#!/usr/bin/env python3
"""Extract Sim's native ABI bindings and build-only resources, never code blobs."""
from pathlib import Path
import struct
from dialogmap import Fs98Pe, SurveyError
from gen_sim_tables import classes
from gen_views_runtime import resource_name


def main():
    pe = Fs98Pe('orig/English/Sim.DLL')
    if pe.uiBase != 0x223c0000 or pe.linkage()['id'] != 0x80000004:
        raise SurveyError('expected the reference Sim image')
    directory = Path('bin/sim-diff')
    directory.mkdir(parents=True, exist_ok=True)
    imports = [binding_entry for binding_entry in pe.imports() if binding_entry['dll'].upper() in ('SIMSUI.DLL','MFC42.DLL')]
    indices = {binding_entry['iat_va']:index for index,binding_entry in enumerate(imports)}
    locals = {}
    lines = ['/* Generated by tools/gen_sim_runtime.py; native ABI metadata. */']

    def add(rva, return_type, parameters, body):
        if rva in locals:raise SurveyError('duplicate local binding')
        name = f'sim_rva_{rva:x}'
        locals[rva] = name
        lines.append(f'static {return_type} TC {name}(void *object{parameters}) '+'{ '+body+' }')

    for kind,(name,ctor,delete,dtor,ddx,getter,size) in enumerate(classes):
        add(delete,'void *',', uint32_t flags',f'return fs98_sim_delete(object, flags, {kind});')
        add(ddx,'void',', void *exchange',f'fs98_sim_exchange(object, exchange, {kind});')
        add(getter,'void *','',f'(void)object; return &s_message_maps[{kind}];')
        help = {0:0x1930,1:0x2170,2:0x2e90,3:0x4710,4:0x5c20,5:0x6820,6:0x6ea0,7:0x7420}[kind]
        add(help,'int',', uint32_t unused, void *info',f'return fs98_sim_help(object, unused, info, {kind});')
        add(help+0x20,'int',', uint32_t window, uint32_t unused',f'return fs98_sim_context(object, window, unused, {kind});')
    for rva,function in ((0x1d20,'empty'),(0x1d40,'disable'),(0x1d50,'enable'),(0x7410,'post_destroy'),
            (0x16c0,'crash_accept'),(0x1710,'crash_cancel'),(0x1690,'crash_close'),(0x1a00,'crash_paint'),
            (0x1fe0,'damage_init'),(0x2b90,'engines_init'),(0x4080,'fuel_init'),(0x5990,'systems_init'),
            (0x65e0,'realism_init'),(0x6dc0,'reliability_init'),(0x7300,'settings_accept'),
            (0x72e0,'settings_cancel'),(0x7380,'settings_close'),(0x5390,'fuel_manual'),(0x53d0,'fuel_selector_changed')):
        add(rva,'void','',f'fs98_sim_{function}(object);')
    add(0x1d30,'void',', uint32_t unused','fs98_sim_empty_arg(object, unused);')
    for rva,function in ((0x1750,'crash_init'),(0x7460,'settings_init')):
        add(rva,'int','',f'return fs98_sim_{function}(object);')
    for rva,function in ((0x21b0,'damage_commit'),(0x2ed0,'engines_commit'),(0x4750,'fuel_validate'),
            (0x4e60,'fuel_error'),(0x5c90,'systems_commit'),(0x6860,'realism_validate'),
            (0x69e0,'realism_error'),(0x6ee0,'reliability_commit'),(0x71d0,'settings_placeholder'),(0x71f0,'zero')):
        add(rva,'int',', uint32_t argument',f'return fs98_sim_{function}(object, argument);')
    for rva,function in ((0x1660,'crash_tick'),(0x6bb0,'zero_message')):
        add(rva,'int',', uint32_t first, uint32_t second',f'return fs98_sim_{function}(object, first, second);')
    for index,rva in enumerate((0x2360,0x23d0,0x2440)):
        add(rva,'void','',f'fs98_sim_damage_radio(object, {index});')
    for index,rva in enumerate((0x2990,0x2a10,0x2a70,0x2ad0,0x2b30)):
        add(rva,'void','',f'fs98_sim_engine_toggle(object, {index});')
    for rva,function in ((0x1910,'notify_delete'),(0x24b0,'static_delete')):
        add(rva,'void *',', uint32_t flags',f'return fs98_sim_{function}(object, flags);')
    lines.append('static const struct sim_import_binding s_import_bindings[] = {')
    for binding_entry in imports:
        name = binding_entry['name']
        ordinal = int(name[1:]) if name.startswith('#') else 0
        lines.append(f'    {{"{binding_entry["dll"]}", "{name}", {ordinal}, 0x{binding_entry["iat_va"]-pe.uiBase:x}}},')
    lines += ['};','static const struct sim_virtual_binding s_virtual_bindings[] = {']
    tables = ((0xa0c8,60),(0xa358,61),(0xa688,61),(0xa988,61),(0xaba8,61),(0xad98,61),(0xaf18,61),(0xb0b8,60),(0xa1b8,48),(0xa450,48))
    for table_index,(table,count) in enumerate(tables):
        for slot in range(count):
            function = pe.va_uint32(pe.uiBase+table+slot*4)-pe.uiBase
            if function in locals:
                binding = f'-1, (void *){locals[function]}'
            else:
                offset = pe.file_offset(function,6)
                if pe.read_bytes(offset,2)!=b'\xff\x25':raise SurveyError(f'unknown virtual {function:#x}')
                binding_entry = pe.read_uint32(offset+2)
                if binding_entry not in indices:raise SurveyError('unknown virtual binding_entry')
                binding = f'{indices[binding_entry]}, 0'
            lines.append(f'    {{{table_index}, {slot}, {binding}}},')
    lines.append('};')
    for kind,class_info in enumerate(classes):
        map = pe.va_uint32(pe.uiBase+class_info[5]+1)
        entries = pe.va_uint32(map+4)
        lines.append(f'static const struct sim_message_entry s_messages{kind}[] = {{')
        for entry in range(64):
            fields = [pe.va_uint32(entries+entry*24+field*4) for field in range(6)]
            if not any(fields):
                lines.append('    {0, 0, 0, 0, 0, 0}');break
            handler = fields[5]-pe.uiBase
            if handler not in locals:raise SurveyError(f'unknown handler {handler:#x}')
            lines.append('    {'+', '.join(f'0x{field:x}' for field in fields[:5])+f', (void *){locals[handler]}'+'},')
        else:raise SurveyError('unterminated message map')
        lines.append('};')
    lines.append('static const struct sim_dialog s_dialogs[] = {')
    factories = {0x1380:'crash',0x11a0:'settings_0',0x1100:'settings_2',0x1240:'settings_3',0x12e0:'settings_5'}
    for dialog in pe.linkage()['dialogs']:
        factory = factories[dialog['create_va']-pe.uiBase]
        lines.append(f'    {{{dialog["id"]}, fs98_sim_create_{factory}, {dialog["flags"]}}},')
    lines += ['    {0, 0, 0}', '};']
    Path('src/sim/sim_runtime_tables.inc').write_text('\n'.join(lines)+'\n')
    ui = Fs98Pe('orig/SIMSUI.DLL')
    export = ui.file_offset(ui.directory(0)[0],40)
    base = ui.read_uint32(export+16)
    names = ui.read_uint32(export+32)
    ordinals = ui.read_uint32(export+36)
    for index in range(ui.read_uint32(export+24)):
        name = ui.read_uint32(ui.file_offset(names+index*4,4))
        if ui.c_string(name)=='?ui_new@@YAPAXI@Z':
            ordinal = base+ui.read_uint16(ui.file_offset(ordinals+index*2,2))
            break
    else:raise SurveyError('SIMSUI anchor missing')
    (directory/'simsui-anchor.def').write_text(f'LIBRARY SIMSUI.DLL\nEXPORTS\n    fs98_sim_simsui_anchor @{ordinal} NONAME\n')
    resources = bytearray(struct.pack('<IIHHHHIHHII',0,32,0xffff,0,0xffff,0,0,0,0,0,0))
    for resource in pe.resources():
        if resource['type']==16:continue
        names = resource_name(resource['type'])+resource_name(resource['id'])
        names += b'\0'*(-len(names)%4)
        resources += struct.pack('<II',resource['size'],8+len(names)+16)
        resources += names+struct.pack('<IHHII',0,0x1030,resource['language'],0,0)
        resources += pe.read_bytes(pe.file_offset(resource['rva'],resource['size']),resource['size'])
        resources += b'\0'*(-len(resources)%4)
    (directory/'sim.res').write_bytes(resources)


if __name__=='__main__':main()
