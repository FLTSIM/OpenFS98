#!/usr/bin/env python3
"""What the native SIMSUI.DLL needs from retail's image, beyond its code.

    python3 -B tools/gen_simsui_native.py [objects...]

SIMSUI exports data as well as code (vtables, message maps, runtime classes, statics), and
its code reaches its own data at retail's RVAs (fs98_simsui_image). The native DLL carries an
image of retail's .rdata and .data (and .data's zero tail), from RVA 0x15000, in which every
pointer retail's relocations list is made ours at load:

  a pointer into that image   -> the same RVA in our copy
  a pointer to a routine      -> our transliteration of it, from the harness's operation table
                                 (tools/difftest/simsui_operations.inc), so a routine bound here
                                 is one that simsuidiff verifies
  a pointer to an import thunk -> the import itself (an MFC base class's virtual)
  a pointer to an unwind funclet or C++ EH table entry -> 0 (only retail's own code used them)

Writes, ABI metadata only, src/simsui/simsui_native_tables.inc, and, as payload under bin/
(never tracked): bin/simsui-native/simsui_image.bin, simsui_image.S (the image and a symbol
for each exported datum), simsui.def (every export at retail's ordinal: routines bound to
ours, data to the image) and simsui.res (retail's resources but its version). With objects
given, the .def's routine names are the symbols nm finds in them (stdcall's @n included).
"""
from pathlib import Path
import re
import struct
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dialogmap import Fs98Pe, SurveyError  # noqa: E402

IMAGE = 'orig/SIMSUI.DLL'
BASE = 0x20470000
START = 0x15000                  # .rdata's start: the image runs from here to .data's end
OPERATIONS = 'tools/difftest/simsui_operations.inc'
TABLES = 'src/simsui/simsui_tables.inc'
OUTPUT = 'src/simsui/simsui_native_tables.inc'
DIRECTORY = Path('bin/simsui-native')
OPERATION = re.compile(r'OPV?\(0x([0-9a-f]+), (\w+)')
FUNCTION = re.compile(r'SIMSUI_FUNCTION\((0x[0-9a-f]+), (\d+), (\d), "([^"]*)"\)')
IMPORT = re.compile(r'SIMSUI_IMPORT\((\d+), (\w+), "([^"]+)", "([^"]+)", (0x[0-9a-f]+),')


def resource_name(name):
    if isinstance(name, int):
        if name > 0xffff:
            raise SurveyError('resource ordinal exceeds WORD')
        return struct.pack('<HH', 0xffff, name)
    return name.encode('utf-16-le') + b'\0\0'


def c_string(pe, rva):
    """a NUL-ended string, read a byte at a time (the last ones end a section's file bytes)"""
    out = bytearray()
    while True:
        byte = pe.read_bytes(pe.file_offset(rva + len(out), 1), 1)[0]
        if not byte:
            return out.decode()
        out.append(byte)


def relocations(pe):
    """every HIGHLOW relocation's RVA"""
    directory = pe.read_uint32(pe.read_uint32(0x3c) + 0xa0)
    size = pe.read_uint32(pe.read_uint32(0x3c) + 0xa4)
    sites = []
    at = 0
    while at < size:
        page = pe.read_uint32(pe.file_offset(directory + at, 4))
        block = pe.read_uint32(pe.file_offset(directory + at + 4, 4))
        for index in range((block - 8) // 2):
            entry = struct.unpack('<H', pe.read_bytes(pe.file_offset(directory + at + 8 + index * 2, 2), 2))[0]
            if entry >> 12 == 3:
                sites.append(page + (entry & 0xfff))
        at += block
    return sites


def main():
    pe = Fs98Pe(IMAGE)
    if pe.uiBase != BASE:
        raise SurveyError(f'{IMAGE}: image base moved')
    text = next(section for section in pe.aSections if section['name'] == '.text')
    data = next(section for section in pe.aSections if section['name'] == '.data')
    end = data['rva'] + data['virtual_size']
    end = (end + 15) & ~15

    ours = {}
    for rva, name in OPERATION.findall(Path(OPERATIONS).read_text()):
        ours.setdefault(int(rva, 16), 'fs98_simsui_' + name)
    tables = Path(TABLES).read_text()
    imports = {int(slot, 16): int(index) for index, _, _, _, slot in IMPORT.findall(tables)}
    functions = {int(rva, 16): name for rva, _, _, name in FUNCTION.findall(tables)}

    def thunk_import(rva):
        offset = pe.file_offset(rva, 6)
        if pe.read_bytes(offset, 2) != b'\xff\x25':
            return None
        return imports.get(pe.read_uint32(offset + 2) - BASE)

    # the image: retail's bytes, its zero tail
    image = bytearray(end - START)
    for section in pe.aSections:
        if section['rva'] >= START and section['rva'] < end:
            size = min(section['raw_size'], section['virtual_size'], end - section['rva'])
            image[section['rva'] - START:section['rva'] - START + size] = pe.read_bytes(section['raw_offset'], size)

    rows = ['/* Generated by tools/gen_simsui_native.py from orig/SIMSUI.DLL: do not edit. ABI metadata only:',
            ' * where retail\'s image holds a pointer, and what it becomes in ours. */',
            f'#define SIMSUI_IMAGE_START {START:#x}',
            f'#define SIMSUI_IMAGE_END {end:#x}']
    counts = {'data': 0, 'code': 0, 'import': 0, 'none': 0}
    unbound = []
    text_end = text['rva'] + text['virtual_size']
    for site in sorted(relocations(pe)):
        if not START <= site < end:
            continue
        value = struct.unpack_from('<I', image, site - START)[0]
        target = value - BASE
        if START <= target < end + 0x10:
            rows.append(f'SIMSUI_RELOC_DATA({site:#x}, {target:#x})')
            counts['data'] += 1
        elif text['rva'] <= target < text_end:
            index = thunk_import(target)
            if index is not None:
                rows.append(f'SIMSUI_RELOC_IMPORT({site:#x}, {index})')
                counts['import'] += 1
            elif target in ours:
                rows.append(f'SIMSUI_RELOC_CODE({site:#x}, {ours[target]})')
                counts['code'] += 1
            elif target >= 0x13560 or target in (0x131f3, 0x13270, 0x1327d, 0x1337f):
                rows.append(f'SIMSUI_RELOC_NONE({site:#x})')     # EH tables: funclets and handlers
                counts['none'] += 1
            else:
                unbound.append((site, target))
        else:
            raise SurveyError(f'{site:#x}: a pointer to {value:#x}, outside the image')
    if unbound:
        raise SurveyError('routines the harness does not verify, in the image: ' +
                          ', '.join(f'{site:#x}->{target:#x}' for site, target in unbound))

    # the exports
    exports = pe.exports()
    ordinal_base = pe.read_uint32(pe.file_offset(pe.read_uint32(pe.read_uint32(0x3c) + 0x78) + 0x10, 4))
    directory = pe.read_uint32(pe.read_uint32(0x3c) + 0x78)
    functions_rva = pe.read_uint32(pe.file_offset(directory + 0x1c, 4))
    count = pe.read_uint32(pe.file_offset(directory + 0x14, 4))
    ordinal_of = {}
    for index in range(count):
        rva = pe.read_uint32(pe.file_offset(functions_rva + index * 4, 4))
        ordinal_of.setdefault(rva, []).append(ordinal_base + index)
    names_rva = pe.read_uint32(pe.file_offset(directory + 0x20, 4))
    ordinals_rva = pe.read_uint32(pe.file_offset(directory + 0x24, 4))
    named = pe.read_uint32(pe.file_offset(directory + 0x18, 4))
    export_rows = []
    for index in range(named):
        name_rva = pe.read_uint32(pe.file_offset(names_rva + index * 4, 4))
        name = c_string(pe, name_rva)
        ordinal = struct.unpack('<H', pe.read_bytes(pe.file_offset(ordinals_rva + index * 2, 2), 2))[0]
        rva = pe.read_uint32(pe.file_offset(functions_rva + ordinal * 4, 4))
        export_rows.append((name, ordinal + ordinal_base, rva))
    if len(export_rows) != len(exports):
        raise SurveyError('export count')

    symbols = {}
    for path in sys.argv[1:]:
        listing = subprocess.run(['i686-w64-mingw32-nm', '-g', '--defined-only', path], check=True,
                                 capture_output=True, text=True).stdout
        for line in listing.splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] == 'T':
                symbol = parts[2][1:] if parts[2].startswith('_') else parts[2]
                symbols[symbol.split('@')[0]] = symbol

    DIRECTORY.mkdir(parents=True, exist_ok=True)
    (DIRECTORY / 'simsui_image.bin').write_bytes(bytes(image))
    assembly = ['/* Generated by tools/gen_simsui_native.py: retail SIMSUI\'s .rdata and .data, and the',
                ' * exported data within them. */',
                '    .data', '    .balign 4096', '    .globl _fs98_simsui_block', '_fs98_simsui_block:',
                '    .incbin "simsui_image.bin"']
    definitions = ['LIBRARY SIMSUI.DLL', 'EXPORTS']
    missing = []
    for name, ordinal, rva in sorted(export_rows, key=lambda row: row[1]):
        if START <= rva < end:
            label = f'_fs98_simsui_datum_{rva:x}'
            if f'    .globl {label}' not in assembly:
                assembly += [f'    .globl {label}', f'    .set {label}, _fs98_simsui_block + {rva - START:#x}']
            definitions.append(f'    {name} = {label[1:]} @{ordinal} DATA')
        else:
            routine = ours.get(rva)
            if routine is None:
                missing.append(f'{name} ({rva:#x})')
                continue
            definitions.append(f'    {name} = {symbols.get(routine, routine)} @{ordinal}')
    if missing:
        raise SurveyError('exported routines the harness does not verify: ' + ', '.join(missing))
    (DIRECTORY / 'simsui_image.S').write_text('\n'.join(assembly) + '\n')
    (DIRECTORY / 'simsui.def').write_text('\n'.join(definitions) + '\n')

    resources = bytearray(struct.pack('<IIHHHHIHHII', 0, 32, 0xffff, 0, 0xffff, 0, 0, 0, 0, 0, 0))
    for resource in pe.resources():
        if resource['type'] == 16:
            continue  # not the retail company's version resource
        names = resource_name(resource['type']) + resource_name(resource['id'])
        names += b'\0' * (-len(names) % 4)
        header = struct.pack('<II', resource['size'], 8 + len(names) + 16)
        header += names + struct.pack('<IHHII', 0, 0x1030, resource['language'], 0, 0)
        resources += header
        resources += pe.read_bytes(pe.file_offset(resource['rva'], resource['size']), resource['size'])
        resources += b'\0' * (-len(resources) % 4)
    (DIRECTORY / 'simsui.res').write_bytes(resources)

    Path(OUTPUT).write_text('\n'.join(rows) + '\n')
    print(f'{OUTPUT}: {counts}; {len(export_rows)} exports; image {len(image):#x} bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
