#!/usr/bin/env python3
"""Extract UTIL.DLL's trigonometry table into a C header.

The quarter-wave cosine table lives at RVA 0x50f6 with a four-byte stride and
129 int16 entries, covering 0 to 0x4000 (a quarter turn).  Values are really
unsigned Q16 -- the helper does `and eax,0xffff` before halving them -- so
entry 0 reads as -1 and means 0xffff, i.e. 1.0.

Usage: tools/gen_util_tables.py [orig/Modules/UTIL.DLL] [src/util/cos_table.inc]
"""
import struct, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'orig/Modules/UTIL.DLL'
DST = sys.argv[2] if len(sys.argv) > 2 else 'src/util/cos_table.inc'
RVA, STRIDE, COUNT = 0x50f6, 4, 130  # 130th entry is read by the interpolator at index 128

b = open(SRC, 'rb').read()
e = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, e + 6)[0]
so = e + 24 + struct.unpack_from('<H', b, e + 20)[0]
off = None
for _ in range(nsec):
    name = b[so:so + 8].rstrip(b'\0').decode()
    vsz, va, rsz, ro = struct.unpack_from('<IIII', b, so + 8)
    if va <= RVA < va + max(vsz, rsz):
        off = ro + (RVA - va)
    so += 40
if off is None:
    sys.exit('RVA 0x%x not in any section of %s' % (RVA, SRC))

vals = [struct.unpack_from('<H', b, off + i * STRIDE)[0] for i in range(COUNT)]
assert vals[0] == 0xffff and vals[128] == 0, 'table does not look like a quarter cosine'

with open(DST, 'w') as f:
    f.write('/* Generated by tools/gen_util_tables.py from %s -- do not edit.\n' % SRC)
    f.write(' * Quarter-wave cosine over 0..0x4000, unsigned Q16, %d entries.\n' % COUNT)
    f.write(' * Entry 0 is 0xffff (1.0) and entry 128 is 0 (cos 90 degrees).\n'
            ' *\n'
            ' * The 130th entry is emitted because the interpolator reads index+1,\n'
            ' * and at index 128 that read runs past the end of this table into the\n'
            ' * arcsine table that begins at +0x2f8.  Retail reads the same bytes;\n'
            ' * they never affect the answer, because the interpolation weight at\n'
            ' * index 128 is zero. */\n\n')
    f.write('static const uint16_t fs98_util_cos_q16[%d] = {\n' % COUNT)
    for i in range(0, COUNT, 8):
        f.write('    ' + ' '.join('0x%04x,' % v for v in vals[i:i + 8]) + '\n')
    f.write('};\n')
# The latitude table, and in fact all of .data: slot 0x44 indexes it with a
# byte offset computed from the latitude, which can run outside the table
# proper, so the whole section is emitted and the table base given as an offset
# into it.  Reading the same bytes retail reads beats guessing at bounds.
DATA_DST = sys.argv[3] if len(sys.argv) > 3 else 'src/util/util_data.inc'
so = e + 24 + struct.unpack_from('<H', b, e + 20)[0]
for _ in range(nsec):
    name = b[so:so + 8].rstrip(b'\0').decode()
    vsz, va, rsz, ro = struct.unpack_from('<IIII', b, so + 8)
    if name == '.data':
        blob = b[ro:ro + vsz] + bytes(max(0, vsz - rsz))
        base = 0x55b4 - va
        with open(DATA_DST, 'w') as f:
            f.write('/* Generated by tools/gen_util_tables.py from %s -- do not edit.\n' % SRC)
            f.write(' * The whole of UTIL.DLL\'s .data (%d bytes).  Slot 0x44 indexes the\n' % vsz)
            f.write(' * latitude table with a byte offset derived from the latitude, which can\n')
            f.write(' * leave the table proper, so the section is kept entire.\n')
            f.write(' *\n')
            f.write(' * The table at +0x%03x is the circumference of the latitude circle in\n' % base)
            f.write(' * metres: 40075000 at the equator, falling to nothing at the pole. */\n\n')
            f.write('#define FS98_UTIL_DATA_SIZE %d\n' % vsz)
            f.write('#define FS98_UTIL_LATTABLE  0x%03x\n\n' % base)
            f.write('static const unsigned char fs98_util_data[%d] = {\n' % vsz)
            for i in range(0, vsz, 12):
                f.write('    ' + ' '.join('0x%02x,' % c for c in blob[i:i + 12]) + '\n')
            f.write('};\n')
        print('wrote %s (%d bytes, table base +0x%03x)' % (DATA_DST, vsz, base))
    so += 40

print('wrote %s (%d entries)' % (DST, COUNT))
