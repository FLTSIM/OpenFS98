#!/usr/bin/env python3
"""Extract WEATHERM.DLL's initialised .data image into C.

WEATHERM keeps its ImportTable, Linkage and its state in one .data section, and
the assembly half addresses the state at fixed offsets.  The reimplementation
keeps one image laid out the same way, so the offsets in a listing can be
grepped for in the C directly, and the difftest can compare the images.

This emits the bytes from +0x98 (after ImportTable and Linkage, which the C
defines itself) to the end of the initialised part: the working variables,
which start zeroed, then three interpolation tables.  There are no pointers in
it; the Linkage's code addresses are checked here against the ones weatherm.c
was transliterated from.

Usage: tools/gen_weatherm_data.py [orig/Modules/WEATHERM.DLL] [src/weatherm/weatherm_data.inc]
"""
import struct, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'orig/Modules/WEATHERM.DLL'
DST = sys.argv[2] if len(sys.argv) > 2 else 'src/weatherm/weatherm_data.inc'

b = open(SRC, 'rb').read()
e = struct.unpack_from('<I', b, 0x3c)[0]
nsec = struct.unpack_from('<H', b, e + 6)[0]
base = struct.unpack_from('<I', b, e + 24 + 28)[0]
so = e + 24 + struct.unpack_from('<H', b, e + 20)[0]
secs = {}
for _ in range(nsec):
    name = b[so:so + 8].rstrip(b'\0').decode()
    vsz, va, rsz, ro = struct.unpack_from('<IIII', b, so + 8)
    secs[name] = (va, vsz, rsz, ro)
    so += 40

va, vsz, rsz, ro = secs['.data']
assert base + va == 0x208f5000, 'WEATHERM .data is not at 0x208f5000'
assert vsz == 0x1c5, '.data virtual size changed'
data = b[ro:ro + vsz]
u32 = lambda o: struct.unpack_from('<I', data, o)[0]

# ImportTable: host, GLOBAL, CHAIN, G3D, MAIN, UTIL, terminator.
assert [u32(8 * i) for i in range(7)] == [1, 2, 4, 14, 3, 20, 0], 'ImportTable'

# Linkage, as weatherm.c's struct describes it.
LINKAGE = [27, 0x208f1020, 0x208f1089, 0, 0, 0,
           0x208f10b9, 0x208f10e5, 0x208f1d70, 0x208f1fb3, 0x208f2406,
           0x208f2a40, 0x208f2a60, 0x208f2a80, 0x208f2b00, 0x208f2bd0,
           0x208f2c30, 0x208f2c50, 0x208f2c80, 0x208f2cb0, 0x208f2e60,
           0x208f2fc0, 0x208f3130, 0x208f3190]
assert [u32(0x38 + 4 * i) for i in range(len(LINKAGE))] == LINKAGE, 'Linkage'

# The working variables start zeroed; the tables follow.
assert data[0x98:0xf3] == bytes(0xf3 - 0x98), 'state is not zero'
assert data[0xf3:0xf6] == b'\x2d\xaa\x0a', 'time-of-day multipliers'
assert struct.unpack_from('<H', data, 0x103)[0] == 0x8001, 'table at +0x103'
assert struct.unpack_from('<H', data, 0x145)[0] == 0x0014, 'table at +0x145'
assert struct.unpack_from('<H', data, 0x181)[0] == 0x5e2d, 'table at +0x181'

body = data[0x98:]
with open(DST, 'w') as f:
    f.write('/* Generated by tools/gen_weatherm_data.py from %s -- do not edit.\n' % SRC)
    f.write(' *\n'
            ' * WEATHERM\'s .data from +0x98 to +0x%x as the file holds it: the\n'
            ' * working variables (zero), two multipliers at +0xf3, and the tables\n'
            ' * at +0x103, +0x145 and +0x181.\n'
            ' */\n' % len(data))
    for i in range(0, len(body), 16):
        f.write('    ' + ' '.join('0x%02x,' % c for c in body[i:i + 16]) + '\n')
