#!/usr/bin/env python3
"""Copy WINDOW.DLL's .text tail (retail code) into bin/ for the WIN-2 read.

The assembly half of WINDOW reads 0x74 bytes kept in .text between the C and
the assembly (.text+0x3490..+0x3504): twenty-two 2^n-1 masks the map's height
interpolates between, 0x18 zero bytes a view's +0x94 is reset from, and the
map's pitch and zoom limit (0x4000, 0x0400).  Those are typed C in window.c
(text_constants).  With GLOBAL +0x390 2 the map's zoom indexes the masks
unclamped, up to 0x803 bytes on: into the assembly's own instructions, which
retail reads as heights (retail bug WIN-2).  This script copies the 0x790
bytes that read can reach, .text+0x3504..+0x3c94, as the file has them
(WINDOW loads at its base, so as memory has it too), into bin/ so no retail
code is in git.  It still checks the masks, zero block and pitch words against
the typed constants' literals.  Delete it when WIN-2 is fixed.

Usage: tools/gen_window_data.py [orig/Modules/WINDOW.DLL]
                                   [bin/window/window_text_tail.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/WINDOW.DLL"
TXT = sys.argv[2] if len(sys.argv) > 2 else "bin/window/window_text_tail.inc"

BASE = 0x20900000
TEXT_LO = 0x20904490
TEXT_HI = 0x20904C94

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".text"]
text = blob[raw + TEXT_LO - BASE - rva:raw + TEXT_HI - BASE - rva]
assert len(text) == TEXT_HI - TEXT_LO, ".text slice short: the tail would be zero-filled"
masks = struct.unpack_from("<22I", text, 0)
# Not every power: 0x1f and 0x3ffff are missing, and retail interpolates
# across the gaps all the same.
assert masks == (0xF, 0x3F, 0x7F, 0xFF, 0x1FF, 0x3FF, 0x7FF, 0xFFF, 0x1FFF,
                 0x3FFF, 0x7FFF, 0xFFFF, 0x1FFFF, 0x7FFFF, 0xFFFFF, 0x1FFFFF,
                 0x3FFFFF, 0x7FFFFF, 0xFFFFFF, 0x1FFFFFF, 0x3FFFFFF,
                 0x7FFFFFF), "zoom masks"
assert text[0x58:0x70] == bytes(0x18), "zero block"
assert struct.unpack_from("<2H", text, 0x70) == (0x4000, 0x0400), "pitch words"

with open(TXT, "w") as output:
    output.write("/* Generated by tools/gen_window_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * WINDOW's .text +0x3504..+0x3c94: the code the map's unclamped zoom\n")
    output.write(" * reads as heights (WIN-2).\n */\n")
    for offset in range(0x74, len(text), 16):
        chunk = text[offset:min(offset + 16, len(text))]
        output.write("    " + " ".join("0x%02x," % value for value in chunk) + "\n")

print("wrote", TXT)
