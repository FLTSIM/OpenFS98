#!/usr/bin/env python3
"""Extract WINDOW.DLL's .data image, and the constants in its .text, into C.

WINDOW keeps ImportTable at +0, Linkage at +0x68, then all of its state in
one 0x8ac-byte .data section (0x400 bytes on disk, the rest zero).  The
reimplementation keeps that layout so the harness can compare the whole
image.  Its only relocations are the Linkage's 32 code pointers, zeroed here
and installed by window.c.

The assembly half also reads 0x74 bytes kept in .text between the C and the
assembly (.text+0x3490..+0x3504): twenty-two 2^n-1 masks the map's height
interpolates between, 0x18 zero bytes a view's +0x94 is reset from, and the
map's pitch and zoom limit (0x4000, 0x0400).  With GLOBAL +0x390 2 the map's
zoom indexes the masks unclamped, up to 0x803 bytes on: into the assembly's
own instructions, which retail reads as heights.  So the second file carries
everything that read can reach, .text+0x3490..+0x3c94, as the file has it
(WINDOW loads at its base, so as memory has it too).

Usage: tools/gen_window_data.py [orig/Modules/WINDOW.DLL]
                                   [src/window/window_data.inc]
                                   [src/window/window_text.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/WINDOW.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/window/window_data.inc"
TXT = sys.argv[3] if len(sys.argv) > 3 else "src/window/window_text.inc"

BASE = 0x20900000
DATA_VA = 0x20909000
SIZE = 0x8AC
IMPORTS = 0x000
LINKAGE = 0x068
TEXT_LO = 0x20904490
TEXT_HI = 0x20904C94

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(IMPORTS + 8 * i) for i in range(13)] == [
    1, 2, 23, 4, 16, 13, 14, 3, 17, 15, 32, 20, 0
], "ImportTable"
assert all(u32(IMPORTS + 8 * i + 4) == 0 for i in range(13)), "import links"
assert u32(LINKAGE) == 10, "module id"
assert [u32(LINKAGE + offset) for offset in (0x0C, 0x10, 0x14)] == \
    [0, 0xC0000000, 0], "Linkage header"
assert data[0xF8:0x109] == b"scenery\\stars.fs\0", "stars file"
assert data[0x288:0x2B0] == (b"SIZE_Y\0\0SIZE_X\0\0Y\0\0\0Default View\0\0\0\0"
                             b"X\0\0\0"), "profile keys"
assert data[0x110:0x12C] == struct.pack("<7I", 0, 0, 0x20, 4, 0, 0, 0), \
    "window list header"
assert data[0x130:0x14C] == struct.pack("<7I", 0, 0, 0x20, 0x18, 0, 0, 0), \
    "layout list header"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size

expected = ([LINKAGE + 4, LINKAGE + 8] +
            [LINKAGE + 0x18 + 4 * i for i in range(30)])
assert sorted(relocations) == sorted(expected), "relocation layout changed"

for offset in relocations:
    value = u32(offset)
    assert 0x20901000 <= value < 0x209071A0, "relocation points outside .text"
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_window_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * WINDOW's complete 0x8ac-byte .data image, with the Linkage's\n")
    output.write(" * code pointers zeroed for window.c to install.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))

rva, virtual_size, raw_size, raw = sections[".text"]
text = blob[raw + TEXT_LO - BASE - rva:raw + TEXT_HI - BASE - rva]
masks = struct.unpack_from("<22I", text, 0)
# Not every power: 0x1f and 0x3ffff are missing, and retail interpolates
# across the gaps all the same.
assert masks == (0xF, 0x3F, 0x7F, 0xFF, 0x1FF, 0x3FF, 0x7FF, 0xFFF, 0x1FFF,
                 0x3FFF, 0x7FFF, 0xFFFF, 0x1FFFF, 0x7FFFF, 0xFFFFF, 0x1FFFFF,
                 0x3FFFFF, 0x7FFFFF, 0xFFFFFF, 0x1FFFFFF, 0x3FFFFFF,
                 0x7FFFFFF), "zoom masks"
assert text[0x58:0x70] == bytes(0x18), "zero block"
assert struct.unpack_from("<2H", text, 0x70) == (0x4000, 0x0400), "pitch words"

with open(TXT, "w") as output:
    output.write("/* Generated by tools/gen_window_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * WINDOW's .text from +0x3490: its 0x74 bytes of constants, then the\n")
    output.write(" * code the map's unclamped zoom reads as heights, to +0x3c94.\n */\n")
    for offset in range(0, len(text), 16):
        chunk = text[offset:offset + 16]
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%03x] = %s\n" % (offset, values))

print("wrote", DST, "and", TXT)
