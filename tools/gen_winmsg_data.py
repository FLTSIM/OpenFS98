#!/usr/bin/env python3
"""Extract WINMSG.DLL's .data image into C.

WINMSG keeps ImportTable at +0, Linkage at +0x30, then all of its state in one
0x4a8-byte .data section (0x200 bytes on disk, the rest zero): the colour of
each of the seven message slots, the fill byte a frame clears the window to,
the slots' accumulated texts, the 0x400-byte line a scrolling message is drawn
from, the window record and the queue.  The reimplementation keeps that
layout, because retail writes outside the line (a window narrower than 30
pixels starts a scrolling message before it, over the slots' texts) and the
harness compares the whole image.  Its only relocations are the Linkage's six
code pointers, zeroed here and installed by winmsg.c.

Usage: tools/gen_winmsg_data.py [orig/Modules/WINMSG.DLL]
                                [src/winmsg/winmsg_data.inc]
"""
import struct
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "orig/Modules/WINMSG.DLL"
DST = sys.argv[2] if len(sys.argv) > 2 else "src/winmsg/winmsg_data.inc"

BASE = 0x20910000
DATA_VA = 0x20914000
SIZE = 0x4A8
LINKAGE = 0x030

blob = open(SRC, "rb").read()
pe = struct.unpack_from("<I", blob, 0x3C)[0]
section_count = struct.unpack_from("<H", blob, pe + 6)[0]
optional = pe + 24
image_base = struct.unpack_from("<I", blob, optional + 28)[0]
section = optional + struct.unpack_from("<H", blob, pe + 20)[0]
sections = {}
for _ in range(section_count):
    name = blob[section:section + 8].rstrip(b"\0").decode()
    virtual_size, rva, raw_size, raw = struct.unpack_from(
        "<IIII", blob, section + 8)
    sections[name] = (rva, virtual_size, raw_size, raw)
    section += 40

assert image_base == BASE, "image base moved"
rva, virtual_size, raw_size, raw = sections[".data"]
assert BASE + rva == DATA_VA and virtual_size == SIZE, ".data moved or resized"
data = bytearray(blob[raw:raw + min(raw_size, SIZE)])
data.extend(bytes(SIZE - len(data)))
u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]

assert [u32(8 * i) for i in range(6)] == [1, 2, 4, 10, 3, 0], "ImportTable"
assert all(u32(8 * i + 4) == 0 for i in range(5)), "import links"
assert u32(LINKAGE) == 22, "module id"
assert [u32(LINKAGE + offset) for offset in (0x0C, 0x10, 0x14)] == [0, 0, 0], \
    "Linkage header"
assert [u32(0x58 + 4 * i) for i in range(7)] == \
    [0, 0x6A, 0x75, 0x75, 0x75, 0x6A, 0x6A], "slot colours"
assert data[0x74] == 0x0B, "fill byte"
assert not any(data[0x78:]), "state is not zero"

rel_rva, rel_size, _, rel_raw = sections[".reloc"]
relocation_data = blob[rel_raw:rel_raw + rel_size]
relocations = []
cursor = 0
while cursor + 8 <= len(relocation_data):
    page, block_size = struct.unpack_from("<II", relocation_data, cursor)
    if block_size == 0:
        break
    for entry_offset in range(8, block_size, 2):
        entry = struct.unpack_from("<H", relocation_data,
                                   cursor + entry_offset)[0]
        if entry >> 12 == 3:
            address = BASE + page + (entry & 0xFFF)
            if DATA_VA <= address < DATA_VA + SIZE:
                relocations.append(address - DATA_VA)
        else:
            assert entry >> 12 == 0, "unexpected relocation type"
    cursor += block_size

expected = [LINKAGE + 4, LINKAGE + 8] + [LINKAGE + 0x18 + 4 * i for i in range(4)]
assert sorted(relocations) == sorted(expected), "relocation layout changed"

for offset in relocations:
    value = u32(offset)
    assert 0x20911000 <= value < 0x20912140, "relocation points outside .text"
    data[offset:offset + 4] = bytes(4)

with open(DST, "w") as output:
    output.write("/* Generated by tools/gen_winmsg_data.py from %s -- do not edit.\n" % SRC)
    output.write(" * WINMSG's complete 0x4a8-byte .data image, with the Linkage's\n")
    output.write(" * code pointers zeroed for winmsg.c to install.\n */\n")
    for offset in range(0, SIZE, 16):
        chunk = data[offset:min(offset + 16, SIZE)]
        if not any(chunk):
            continue
        values = " ".join("0x%02x," % value for value in chunk)
        output.write("    [0x%04x] = %s\n" % (offset, values))

print("wrote", DST)
