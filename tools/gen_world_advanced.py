#!/usr/bin/env python3
"""Recover Advanced Weather's six-class ABI; never extract code/resources."""
from pathlib import Path
import re
from dialogmap import Fs98Pe, SurveyError
from gen_world_tables import instructions, object_calls, cleanup_imports

# Parent allocation order; tab order is clouds, wind, temperature, visibility,
# pressure. Values are reference RVAs, not callable addresses in the port.
CLASSES = [
    ('parent', 0x1e20, 0x1f50, 0x1f70, 0x2088, 0x20b0, 0x21c0, 0x1e0f8, 0x2658, 0x6a5, 14),
    ('clouds', 0x7250, 0x73c0, 0x73e0, 0x7550, 0x7550, 0x76d0, 0x1f0f8, 0x21a0, 0x6a7, 20),
    ('temperature', 0xe7d0, 0xe900, 0xe920, 0xea30, 0xea30, 0xeb30, 0x20538, 0x199c, 0x6b7, 13),
    ('visibility', 0xfbc0, 0xfc50, 0xfc70, 0xfcf0, 0xfcf0, 0xfd40, 0x206e8, 0x12e4, 0x6b9, 3),
    ('wind', 0x119b0, 0x11b30, 0x11b50, 0x11cb0, 0x11cb0, 0x11e30, 0x20c38, 0x2210, 0x6bb, 20),
    ('pressure', 0x9c30, 0x9cf0, 0x9d10, 0x9dc0, 0x9dc0, 0x9e50, 0x1f4e8, 0x15a4, 0x6af, 7),
]


def graph(ops):
    return object_calls([op.replace('call   0x22409a42', 'call   DWORD PTR ds:0x224155a4')
                        .replace('call   0x22409a48', 'call   DWORD PTR ds:0x224155a0') for op in ops])


def main():
    pe = Fs98Pe('orig/English/World.DLL')
    if pe.uiBase != 0x223f0000 or pe.linkage()['id'] != 0x80000006:
        raise SurveyError('expected retail World')
    lines = ['/* Generated by tools/gen_world_advanced.py; ABI metadata only. */']
    constructors, destructors, bases = set(), set(), set()
    records = []
    for name, start, scalar, destroy, destroy_end, ddx, map_getter, table, size, template, count in CLASSES:
        ctor_ops, dtor_ops = instructions(start, scalar), instructions(destroy, destroy_end)
        ctor, dtor = graph(ctor_ops), list(reversed(graph(dtor_ops)))
        if len(ctor) != count + 1 or [off for off, _ in ctor] != [off for off, _ in dtor]:
            raise SurveyError(f'{name}: changed lifetime graph')
        cleanup = cleanup_imports(pe, ctor_ops, count)
        if cleanup != cleanup_imports(pe, dtor_ops, count) or cleanup != dict(dtor[:-1]):
            raise SurveyError(f'{name}: changed unwind graph')
        stores = [int(match[1], 16) for op in ctor_ops if (match := re.fullmatch(r'mov\s+DWORD PTR \[esi\],0x([0-9a-f]+)', op))]
        if stores != [pe.uiBase + table] or pe.va_uint32(pe.uiBase + table + 4) != pe.uiBase + scalar:
            raise SurveyError(f'{name}: changed vtable')
        lines += [f'static const struct fs98_world_control s_advanced_{name}_controls[] = {{']
        lines += [f'    {{0x{off:x}, 0x{construct:x}, 0x{destruct:x}}},' for (off, construct), (_, destruct) in zip(ctor[1:], dtor[1:])]
        lines += ['};', f'static const uint32_t s_advanced_{name}_cleanup[] = {{']
        lines += [f'    0x{cleanup.get(off, destruct):x},' for off, destruct in dtor[1:]]
        lines += ['};', f'static const uint16_t s_advanced_{name}_ddx[][2] = {{']
        bindings, offset, control_id = [], None, None
        for op in instructions(ddx, map_getter):
            match = re.search(r'(?:lea\s+\w+,\[esi\+0x|add\s+esi,0x)([0-9a-f]+)', op)
            if match: offset = int(match[1], 16)
            match = re.fullmatch(r'push\s+(0x[0-9a-f]+)', op)
            if match: control_id = int(match[1], 16)
            if op == 'call   0x224099c4':
                if offset is None or control_id is None: raise SurveyError(f'{name}: unknown DDX')
                bindings.append((offset, control_id)); offset = control_id = None
        if sorted(off for off, _ in bindings) != sorted(off for off, _ in ctor[1:]):
            raise SurveyError(f'{name}: DDX does not cover controls')
        lines += [f'    {{0x{off:x}, 0x{control_id:x}}},' for off, control_id in bindings]
        lines += ['};', f'static const uint32_t s_advanced_{name}_vtables[] = {{']
        lines += [f'    0x{pe.va_uint32(pe.uiBase + table + index * 4) - pe.uiBase:x},' for index in range(61 if name != 'parent' else 60)]
        lines += ['};']
        getter_ops = instructions(map_getter, map_getter + 0x10)
        maps = [int(match[1], 16) for op in getter_ops if (match := re.fullmatch(r'mov\s+eax,0x([0-9a-f]+)', op))]
        if len(maps) != 1: raise SurveyError(f'{name}: unknown map getter')
        message_map = maps[0]
        entries = pe.va_uint32(message_map + 4)
        lines += [f'static const uint32_t s_advanced_{name}_messages[][6] = {{']
        help_handler = None
        for index in range(64):
            fields = [pe.va_uint32(entries + index * 24 + field * 4) for field in range(6)]
            lines.append('    {' + ', '.join(f'0x{field:x}' for field in fields) + '},')
            if fields[0] == 0x53: help_handler = fields[5]
            if not any(fields): break
        else: raise SurveyError(f'{name}: unterminated message map')
        lines += ['};']
        if help_handler is None: raise SurveyError(f'{name}: missing help')
        pushes = [int(match[1], 16) for op in instructions(help_handler - pe.uiBase, help_handler - pe.uiBase + 0x20)
                  if (match := re.fullmatch(r'push\s+(0x[0-9a-f]+)', op))]
        if len(pushes) != 3 or pushes[1] != 12: raise SurveyError(f'{name}: unknown help')
        lines += [f'static const uint32_t s_advanced_{name}_help[] = {{']
        for index in range(64):
            pair = [pe.va_uint32(pushes[0] + index * 8 + field * 4) for field in range(2)]
            lines.append('    ' + ', '.join(f'0x{field:x}' for field in pair) + ',')
            if not any(pair): break
        else: raise SurveyError(f'{name}: unterminated help')
        lines += ['};']
        # Page templates must be recovered from their base constructor calls.
        if f'push   0x{template:x}' not in ctor_ops:
            raise SurveyError(f'{name}: template changed')
        records.append(f'    {{s_advanced_{name}_controls, s_advanced_{name}_cleanup, s_advanced_{name}_ddx, s_advanced_{name}_help, {count}, 0x{template:x}, 0x{size:x}, 0x{ctor[0][1]:x}, 0x{dtor[0][1]:x}, 0x{table:x}, 0x{start:x}, 0x{destroy:x}, 0x{scalar:x}}},')
        constructors.update(slot for _, slot in ctor[1:]); destructors.update(slot for _, slot in dtor); bases.add(ctor[0][1])
    lines += ['static const struct world_advanced_class s_advanced_classes[] = {'] + records + ['};']
    Path('src/world/world_advanced_tables.inc').write_text('\n'.join(lines) + '\n')
    hooks = ['/* Generated by tools/gen_world_advanced.py; imported class ABI. */']
    for macro, slots in [('WORLD_ADVANCED_BASE_HOOK', bases), ('WORLD_CTOR_HOOK', constructors), ('WORLD_DTOR_HOOK', destructors)]:
        hooks += [f'{macro}({slot:x})' for slot in sorted(slots)]
    Path('src/world/world_advanced_hooks.inc').write_text('\n'.join(hooks) + '\n')
    data = ['/* Generated by tools/gen_world_advanced.py; retail lookup metadata. */', 'static const uint32_t s_cloud_amount_titles[] = {']
    data += [f'    0x{pe.va_uint32(0x2240ef5c + index * 8):x},' for index in range(9)]
    data += ['};', 'static const uint32_t s_cloud_types[] = {']
    data += [f'    0x{pe.va_uint32(0x2241433c + index * 4):x},' for index in range(12)]
    data += ['};']
    Path('src/world/world_advanced_data.inc').write_text('\n'.join(data) + '\n')


if __name__ == '__main__':
    main()
