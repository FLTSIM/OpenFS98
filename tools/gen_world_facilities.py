#!/usr/bin/env python3
"""Extract facilities class metadata; no code or resource payloads."""
from pathlib import Path
import re
from dialogmap import Fs98Pe, SurveyError
from gen_world_tables import instructions, object_calls


def facilities_cleanup(pe, ops):
    handlers = [int(match[1], 16) for op in ops[:5]
                if (match := re.fullmatch(r'push\s+0x([0-9a-f]+)', op)) and int(match[1], 16) != 0xffffffff]
    if len(handlers) != 1:
        raise SurveyError('unknown facilities EH registration')
    info = pe.va_uint32(handlers[0] + 1)
    if pe.va_uint32(info) != 0x19930520 or pe.va_uint32(info + 4) != 9:
        raise SurveyError('facilities EH graph changed')
    table = pe.va_uint32(info + 8)
    result = {}
    for index in range(9):
        if pe.va_uint32(table + index * 8) != (index - 1) & 0xffffffff:
            raise SurveyError('nonlinear facilities EH graph')
        action = pe.va_uint32(table + index * 8 + 4)
        offset = 0
        for op in instructions(action - pe.uiBase, action - pe.uiBase + 24):
            match = re.fullmatch(r'add\s+ecx,0x([0-9a-f]+)', op)
            if match:
                offset = int(match[1], 16)
            if op == 'jmp    0x22409aa2':
                op = instructions(0x19aa2, 0x19aa8)[0]
            match = re.fullmatch(r'jmp\s+DWORD PTR ds:0x([0-9a-f]+)', op)
            if match:
                result[offset] = int(match[1], 16) - pe.uiBase
                break
        else:
            raise SurveyError('unknown facilities cleanup action')
    return result


def main():
    pe = Fs98Pe('orig/English/World.DLL')
    if pe.uiBase != 0x223f0000 or pe.linkage()['id'] != 0x80000006:
        raise SurveyError('expected reference World')
    ctor_asm = instructions(0x16f00, 0x16ff0)
    dtor_asm = instructions(0x17010, 0x170f0)
    normalize = lambda ops: [op.replace('call   0x22409a42', 'call   DWORD PTR ds:0x224155a4').replace('call   0x22409aa2', 'call   DWORD PTR ds:0x22415564') for op in ops]
    ctor, dtor = object_calls(normalize(ctor_asm)), list(reversed(object_calls(normalize(dtor_asm))))
    if len(ctor) != 10 or [offset for offset, _ in ctor] != [offset for offset, _ in dtor]:
        raise SurveyError('facilities control graph moved')
    unwind = facilities_cleanup(pe, ctor_asm)
    if unwind != facilities_cleanup(pe, dtor_asm) or unwind != dict(dtor[:-1]):
        raise SurveyError('facilities cleanup graph moved')
    lines = ['/* Generated by tools/gen_world_facilities.py; ABI metadata only. */',
             'static const struct fs98_world_control s_facilities_controls[] = {']
    lines += [f'    {{0x{offset:x}, 0x{construct:x}, 0x{destroy:x}}},'
              for (offset, construct), (_, destroy) in zip(ctor[1:], dtor[1:])]
    lines += ['};', 'static const uint32_t s_facilities_cleanup[] = {']
    lines += [f'    0x{unwind.get(offset, destroy):x},' for offset, destroy in dtor[1:]]
    lines += ['};', 'static const uint16_t s_facilities_ddx[][2] = {']
    bindings = []
    offset = control_id = None
    for op in instructions(0x170f0, 0x171b0):
        match = re.search(r'(?:lea\s+\w+,\[esi\+0x|add\s+esi,0x)([0-9a-f]+)', op)
        if match:
            offset = int(match[1], 16)
        match = re.fullmatch(r'push\s+0x([0-9a-f]+)', op)
        if match:
            control_id = int(match[1], 16)
        if op == 'call   0x224099c4':
            if offset is None or control_id is None:
                raise SurveyError('unknown facilities DDX')
            bindings.append((offset, control_id))
            offset = control_id = None
    if sorted(offset for offset, _ in bindings) != sorted(offset for offset, _ in ctor[1:]):
        raise SurveyError('facilities DDX differs from controls')
    lines += [f'    {{0x{offset:x}, 0x{control_id:x}}},' for offset, control_id in bindings]
    lines += ['};', 'static const uint32_t s_facilities_help[] = {']
    pushes = [int(match[1], 16) for op in instructions(0x195e0, 0x19600)
              if (match := re.fullmatch(r'push\s+0x([0-9a-f]+)', op))]
    if len(pushes) != 3 or pushes[1] != 12:
        raise SurveyError('facilities help changed')
    for index in range(64):
        control_id, topic = pe.va_uint32(pushes[0] + index * 8), pe.va_uint32(pushes[0] + index * 8 + 4)
        lines.append(f'    0x{control_id:x}, 0x{topic:x},')
        if not control_id and not topic:
            break
    else:
        raise SurveyError('unterminated facilities help map')
    vtables = [int(match[1], 16) for op in ctor_asm
               if (match := re.fullmatch(r'mov\s+DWORD PTR \[esi\],0x([0-9a-f]+)', op))]
    if vtables != [0x224116b8] or pe.va_uint32(vtables[0] + 4) != 0x22406ff0:
        raise SurveyError('facilities vtable changed')
    lines += ['};', '#define WORLD_FACILITIES_VTABLE_RVA 0x216b8',
              f'#define WORLD_FACILITIES_BASE_CTOR 0x{ctor[0][1]:x}',
              f'#define WORLD_FACILITIES_BASE_DTOR 0x{dtor[0][1]:x}']
    if pe.va_uint32(0x224115a8) != 0x223f5d40:
        raise SurveyError('facilities base message map moved')
    lines += ['static const uint32_t s_facilities_vtable_rvas[] = {']
    lines += [f'    0x{pe.va_uint32(0x224116b8 + index * 4) - pe.uiBase:x},' for index in range(60)]
    lines += ['};', 'static const uint32_t s_facilities_messages[][6] = {']
    for index in range(11):
        fields = [pe.va_uint32(0x224115b0 + index * 24 + field * 4) for field in range(6)]
        lines.append('    {' + ', '.join(f'0x{value:x}' for value in fields) + '},')
        if not any(fields): break
    else: raise SurveyError('facilities message map not terminated')
    if index != 10: raise SurveyError('facilities message count changed')
    lines += ['};']
    spin_stores = [int(match[1], 16) for op in ctor_asm
                   if (match := re.fullmatch(r'mov\s+DWORD PTR \[ebx\],0x([0-9a-f]+)', op))]
    if spin_stores != [0x224117a8]:
        raise SurveyError('facilities local spin vtable changed')
    lines += [f'#define WORLD_FACILITIES_SPIN_VTABLE_RVA 0x{spin_stores[0] - pe.uiBase:x}']
    for name, address, count in [('regions', 0x22414468, 9), ('countries', 0x22414520, 50)]:
        lines += [f'static const uint32_t s_facilities_{name}[][5] = {{']
        for index in range(count):
            values = [pe.va_uint32(address + index * 20 + field * 4) for field in range(5)]
            lines.append('    {' + ', '.join(f'0x{value:x}' for value in values) + '},')
        lines += ['};']
    Path('src/world/world_facilities_tables.inc').write_text('\n'.join(lines) + '\n')
    hooks = ['/* Generated by tools/gen_world_facilities.py; import ABI metadata. */']
    for macro, slots in [('WORLD_BASE_HOOK', [ctor[0][1]]),
                         ('WORLD_CTOR_HOOK', sorted({slot for _, slot in ctor[1:]})),
                         ('WORLD_DTOR_HOOK', sorted({slot for _, slot in dtor}))]:
        hooks += [f'{macro}({slot:x})' for slot in slots]
    Path('src/world/world_facilities_hooks.inc').write_text('\n'.join(hooks) + '\n')


if __name__ == '__main__':
    main()
