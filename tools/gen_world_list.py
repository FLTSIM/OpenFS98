#!/usr/bin/env python3
"""Extract scenery-area-list class metadata; no code or resource payloads."""
from pathlib import Path
import re
from dialogmap import Fs98Pe, SurveyError
from gen_world_tables import instructions, object_calls, cleanup_imports


def main():
    pe = Fs98Pe('orig/English/World.DLL')
    if pe.uiBase != 0x223f0000 or pe.linkage()['id'] != 0x80000006:
        raise SurveyError('expected reference World')
    ctor_asm = instructions(0xa260, 0xa380)
    dtor_asm = instructions(0xa3a0, 0xa4b0)
    ctor, dtor = object_calls(ctor_asm), list(reversed(object_calls(dtor_asm)))
    if len(ctor) != 15 or [offset for offset, _ in ctor] != [offset for offset, _ in dtor]:
        raise SurveyError('list control graph moved')
    unwind = cleanup_imports(pe, ctor_asm, 14)
    if unwind != cleanup_imports(pe, dtor_asm, 14) or unwind != dict(dtor[:-1]):
        raise SurveyError('list cleanup graph moved')
    lines = ['/* Generated by tools/gen_world_list.py; ABI metadata only. */',
             'static const struct fs98_world_control s_list_controls[] = {']
    lines += [f'    {{0x{offset:x}, 0x{construct:x}, 0x{destroy:x}}},'
              for (offset, construct), (_, destroy) in zip(ctor[1:], dtor[1:])]
    lines += ['};', 'static const uint16_t s_list_ddx[][2] = {']
    bindings = []
    offset = control_id = None
    for op in instructions(0xa4b0, 0xa5c0):
        match = re.search(r'(?:lea\s+\w+,\[esi\+0x|add\s+esi,0x)([0-9a-f]+)', op)
        if match:
            offset = int(match[1], 16)
        match = re.fullmatch(r'push\s+0x([0-9a-f]+)', op)
        if match:
            control_id = int(match[1], 16)
        if op == 'call   0x224099c4':
            if offset is None or control_id is None:
                raise SurveyError('unknown list DDX')
            bindings.append((offset, control_id))
            offset = control_id = None
    if sorted(offset for offset, _ in bindings) != sorted(offset for offset, _ in ctor[1:]):
        raise SurveyError('list DDX differs from controls')
    lines += [f'    {{0x{offset:x}, 0x{control_id:x}}},' for offset, control_id in bindings]
    lines += ['};', 'static const uint32_t s_list_help[] = {']
    pushes = [int(match[1], 16) for op in instructions(0xacd0, 0xacf0)
              if (match := re.fullmatch(r'push\s+0x([0-9a-f]+)', op))]
    if len(pushes) != 3 or pushes[1] != 12:
        raise SurveyError('list help changed')
    for index in range(64):
        control_id, topic = pe.va_uint32(pushes[0] + index * 8), pe.va_uint32(pushes[0] + index * 8 + 4)
        lines.append(f'    0x{control_id:x}, 0x{topic:x},')
        if not control_id and not topic:
            break
    else:
        raise SurveyError('unterminated list help map')
    vtables = [int(match[1], 16) for op in ctor_asm
               if (match := re.fullmatch(r'mov\s+DWORD PTR \[esi\],0x([0-9a-f]+)', op))]
    if vtables != [0x2240f750] or pe.va_uint32(vtables[0] + 4) != 0x223fa380:
        raise SurveyError('list vtable changed')
    lines += ['};', '#define WORLD_LIST_VTABLE_RVA 0x1f750',
              f'#define WORLD_LIST_BASE_CTOR 0x{ctor[0][1]:x}',
              f'#define WORLD_LIST_BASE_DTOR 0x{dtor[0][1]:x}']
    # The populated-row switch maps exactly five layers to resource ids.
    resources = []
    targets = [pe.va_uint32(0x223fab38 + index * 4) for index in range(5)]
    for target in targets:
        ids = [int(match[1], 16) for op in instructions(target - pe.uiBase, target - pe.uiBase + 28)
               if (match := re.fullmatch(r'push\s+0x(f8[0-9a-f]{2})', op))]
        if not ids:
            raise SurveyError('list layer string recipe changed')
        resources.append(ids[0])
    switch = pe.read_bytes(pe.file_offset(0xab50, 41), 41)
    expected = bytes(index // 10 if index % 10 == 0 else 5 for index in range(41))
    if switch != expected or pe.va_uint32(0x223fab38 + 5 * 4) != 0x223fa9c0:
        raise SurveyError('area-list layer switch/default changed')
    lines.append('static const uint32_t s_list_layer_strings[] = {' + ', '.join(hex(value) for value in resources) + '};')
    if pe.va_uint32(0x2240f658) != 0x223f5d40:
        raise SurveyError('area-list base message map moved')
    lines += ['static const uint32_t s_list_vtable_rvas[] = {']
    lines += [f'    0x{pe.va_uint32(0x2240f750 + index * 4) - pe.uiBase:x},' for index in range(60)]
    lines += ['};', 'static const uint32_t s_list_messages[][6] = {']
    for index in range(10):
        fields = [pe.va_uint32(0x2240f660 + index * 24 + field * 4) for field in range(6)]
        lines.append('    {' + ', '.join(f'0x{value:x}' for value in fields) + '},')
        if not any(fields): break
    else: raise SurveyError('area-list message map not terminated')
    if index != 9: raise SurveyError('area-list message count changed')
    lines += ['};']
    Path('src/world/world_list_tables.inc').write_text('\n'.join(lines) + '\n')
    hooks = ['/* Generated by tools/gen_world_list.py; import ABI metadata. */']
    for macro, slots in [('WORLD_BASE_HOOK', [ctor[0][1]]),
                         ('WORLD_CTOR_HOOK', sorted({slot for _, slot in ctor[1:]})),
                         ('WORLD_DTOR_HOOK', sorted({slot for _, slot in dtor}))]:
        hooks += [f'{macro}({slot:x})' for slot in slots]
    Path('src/world/world_list_hooks.inc').write_text('\n'.join(hooks) + '\n')


if __name__ == '__main__':
    main()
