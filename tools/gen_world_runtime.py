#!/usr/bin/env python3
"""Extract the partial area-class native bindings and build-only resources."""
from pathlib import Path
import struct
from dialogmap import Fs98Pe, SurveyError
from gen_views_runtime import resource_name


def main():
    pPe = Fs98Pe('orig/English/World.DLL')
    if pPe.uiBase != 0x223f0000 or pPe.linkage()['id'] != 0x80000006:
        raise SurveyError('expected retail World')
    pOutput = Path('bin/world-diff')
    pOutput.mkdir(parents=True, exist_ok=True)
    aImports = [dImport for dImport in pPe.imports() if dImport['dll'].upper() in ('MFC42.DLL', 'SIMSUI.DLL')]
    dIndices = {dImport['iat_va']: iIndex for iIndex, dImport in enumerate(aImports)}
    dLocals = {0xbc70: ('void *', ', uint32 uiFlags', 'return fs98_world_area_delete(pObject, uiFlags);'),
        0x2d00: ('void', ', uint32 uiUnused', '(void)pObject; (void)uiUnused;'),
        0x2d10: ('void', '', '(void)pObject;'),
        0x2d20: ('void', '', 'EnableWindow((HWND)WORLD_U32(pObject, 0x20), 0);'),
        0x2d30: ('void', '', 'EnableWindow((HWND)WORLD_U32(pObject, 0x20), 1);'),
        0xbed0: ('void *', '', '(void)pObject; return &s_stMessageMap;'),
        0xbdc0: ('void', ', void *pExchange', 'fs98_world_area_exchange(pObject, pExchange);'),
        0xbef0: ('int', '', 'return fs98_world_area_init(pObject);'),
        0xc2e0: ('void', '', 'fs98_world_area_accept(pObject);'),
        0xc2c0: ('void', '', 'fs98_world_area_cancel(pObject);'),
        0xc610: ('int', ', uint32 uiValue', 'return fs98_world_area_validate(pObject, uiValue);'),
        0xc660: ('int', ', uint32 uiValue', 'return fs98_world_area_error(pObject, uiValue);'),
        0xc720: ('void', '', 'fs98_world_area_path_changed(pObject);'),
        0xc5d0: ('int', ', uint32 uiUnused, void *pInfo', 'return fs98_world_area_help(pObject, uiUnused, pInfo);'),
        0xc5f0: ('int', ', uint32 uiWindow, uint32 uiUnused', 'return fs98_world_area_context(pObject, uiWindow, uiUnused);')}
    aLines = ['/* Generated by tools/gen_world_runtime.py; native ABI metadata only. */']
    for uiRva, (pcReturn, pcArguments, pcBody) in dLocals.items():
        aLines.append(f'static {pcReturn} TC world_rva_{uiRva:x}(void *pObject{pcArguments}) {{ {pcBody} }}')
    aLines += ['static const struct world_import_binding s_astImports[] = {']
    for dImport in aImports:
        pcName = dImport['name']
        uiOrdinal = int(pcName[1:]) if pcName.startswith('#') else 0
        aLines.append(f'    {{"{dImport["dll"]}", "{pcName}", {uiOrdinal}, 0x{dImport["iat_va"] - pPe.uiBase:x}}},')
    aLines += ['};', 'static const struct world_virtual_binding s_astVirtuals[] = {']
    for iSlot in range(60):
        uiVa = pPe.va_uint32(0x2240fc38 + iSlot * 4)
        uiRva = uiVa - pPe.uiBase
        if uiRva in dLocals:
            pcBinding = f'-1, (void *)world_rva_{uiRva:x}'
        else:
            iOffset = pPe.file_offset(uiRva, 6)
            if pPe.read_bytes(iOffset, 2) != b'\xff\x25':
                raise SurveyError(f'unknown area virtual {uiVa:#x}')
            uiIat = pPe.read_uint32(iOffset + 2)
            pcBinding = f'{dIndices[uiIat]}, 0'
        aLines.append(f'    {{{iSlot}, {pcBinding}}},')
    aLines += ['};', 'static const struct world_message_entry s_astMessages[] = {']
    uiEntries = pPe.va_uint32(0x2240fbd0 + 4)
    for iIndex in range(64):
        aFields = [pPe.va_uint32(uiEntries + iIndex * 24 + iField * 4) for iField in range(6)]
        if not any(aFields):
            aLines.append('    {0, 0, 0, 0, 0, 0}')
            break
        uiRva = aFields[5] - pPe.uiBase
        if uiRva not in dLocals:
            raise SurveyError('unknown area handler')
        aLines.append('    {' + ', '.join(hex(uiField) for uiField in aFields[:5]) + f', (void *)world_rva_{uiRva:x}' + '},')
    else:
        raise SurveyError('unterminated area map')
    aLines += ['};', 'static const struct world_dialog s_astDialogs[] = {']
    for dDialog in pPe.linkage()['dialogs']:
        if dDialog['id'] in (0x13080003, 0x13080004):
            pcKind = 'add' if dDialog['id'] == 0x13080003 else 'edit'
            aLines.append(f'    {{0x{dDialog["id"]:x}, fs98_world_area_create_{pcKind}, {dDialog["flags"]}}},')
    aLines += ['    {0, 0, 0}', '};']
    Path('src/world/world_runtime_tables.inc').write_text('\n'.join(aLines) + '\n')
    pUi = Fs98Pe('orig/SIMSUI.DLL')
    iExport = pUi.file_offset(pUi.directory(0)[0], 40)
    uiBase = pUi.read_uint32(iExport + 16)
    uiNames, uiOrdinals = pUi.read_uint32(iExport + 32), pUi.read_uint32(iExport + 36)
    for iIndex in range(pUi.read_uint32(iExport + 24)):
        uiName = pUi.read_uint32(pUi.file_offset(uiNames + iIndex * 4, 4))
        if pUi.c_string(uiName) == '?ui_new@@YAPAXI@Z':
            uiOrdinal = uiBase + pUi.read_uint16(pUi.file_offset(uiOrdinals + iIndex * 2, 2))
            break
    else:
        raise SurveyError('SIMSUI anchor missing')
    (pOutput / 'simsui-anchor.def').write_text(f'LIBRARY SIMSUI.DLL\nEXPORTS\n    fs98_world_simsui_anchor @{uiOrdinal} NONAME\n')
    byResources = bytearray(struct.pack('<IIHHHHIHHII', 0, 32, 0xffff, 0, 0xffff, 0, 0, 0, 0, 0, 0))
    for dResource in pPe.resources():
        if dResource['type'] == 16:
            continue
        byNames = resource_name(dResource['type']) + resource_name(dResource['id'])
        byNames += b'\0' * (-len(byNames) % 4)
        byResources += struct.pack('<II', dResource['size'], 8 + len(byNames) + 16)
        byResources += byNames + struct.pack('<IHHII', 0, 0x1030, dResource['language'], 0, 0)
        byResources += pPe.read_bytes(pPe.file_offset(dResource['rva'], dResource['size']), dResource['size'])
        byResources += b'\0' * (-len(byResources) % 4)
    (pOutput / 'world.res').write_bytes(byResources)


if __name__ == '__main__':
    main()
