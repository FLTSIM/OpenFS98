#!/usr/bin/env python3
"""Extract the time/season parent and both tab-page ABI graphs."""
from pathlib import Path
import re
from dialogmap import Fs98Pe, SurveyError
from gen_world_tables import instructions, object_calls, cleanup_imports


def main():
    pe = Fs98Pe('orig/English/World.DLL')
    if pe.uiBase != 0x223f0000 or pe.linkage()['id'] != 0x80000006:
        raise SurveyError('expected reference World')
    classes = [
        ('parent', 0x5b20, 0x5bd0, 0x5bf0, 0x5ca0, 0x5cc0, 0x5d40, 0x2240ec48, 60, 6, 0x6aa, 0x212c, 0x2240ebf8, 0x6130),
        ('season', 0x4110, 0x4270, 0x4290, 0x43d0, 0x43d0, 0x4510, 0x2240e7a0, 61, 17, 0x6a9, 0x1c08, 0x2240e6c0, 0x4750),
        ('clock', 0x4d20, 0x4eb0, 0x4ed0, 0x5040, 0x5040, 0x51c0, 0x2240eac8, 61, 20, 0x6b8, 0x1df0, 0x2240ea00, 0x5490),
    ]
    lines = ['/* Generated by tools/gen_world_time.py; ABI metadata only. */']
    all_ctors, all_dtors = set(), set()
    for name, ctor_start, ctor_end, dtor_start, dtor_end, ddx_start, ddx_end, vtable, slots, count, template, size, message_map, help_start in classes:
        ctor_asm, dtor_asm = instructions(ctor_start, ctor_end), instructions(dtor_start, dtor_end)
        def graph(ops):
            return object_calls([op.replace('call   0x22409a42', 'call   DWORD PTR ds:0x224155a4').replace('call   0x22409a48', 'call   DWORD PTR ds:0x224155a0') for op in ops])
        ctor, dtor = graph(ctor_asm), list(reversed(graph(dtor_asm)))
        unwind = cleanup_imports(pe, ctor_asm, count)
        if len(ctor) != count + 1 or [off for off, _ in ctor] != [off for off, _ in dtor] or unwind != cleanup_imports(pe, dtor_asm, count) or unwind != dict(dtor[:-1]):
            raise SurveyError(f'{name} lifetime graph moved')
        lines += [f'static const struct fs98_world_control s_time_{name}_controls[] = {{']
        lines += [f'    {{0x{off:x}, 0x{construct:x}, 0x{destroy:x}}},' for (off, construct), (_, destroy) in zip(ctor[1:], dtor[1:])]
        lines += ['};', f'static const uint32_t s_time_{name}_cleanup[] = {{']
        lines += [f'    0x{unwind.get(off, destroy):x},' for off, destroy in dtor[1:]]
        lines += ['};', f'static const uint16_t s_time_{name}_ddx[][2] = {{']
        bindings = []; offset = control_id = None
        for op in instructions(ddx_start, ddx_end):
            match = re.search(r'(?:lea\s+\w+,\[esi\+0x|add\s+esi,0x)([0-9a-f]+)', op)
            if match: offset = int(match[1], 16)
            match = re.fullmatch(r'push\s+0x([0-9a-f]+)', op)
            if match: control_id = int(match[1], 16)
            if op == 'call   0x224099c4':
                if offset is None or control_id is None: raise SurveyError('unknown time DDX')
                bindings.append((offset, control_id)); offset = control_id = None
        if sorted(off for off, _ in bindings) != sorted(off for off, _ in ctor[1:]): raise SurveyError('time DDX graph changed')
        lines += [f'    {{0x{off:x}, 0x{control_id:x}}},' for off, control_id in bindings]
        lines += ['};', f'static const uint32_t s_time_{name}_help[] = {{']
        pushes = [int(match[1], 16) for op in instructions(help_start, help_start + 0x20) if (match := re.fullmatch(r'push\s+0x([0-9a-f]+)', op))]
        if len(pushes) != 3 or pushes[1] != 12: raise SurveyError('unknown time help')
        for index in range(64):
            control_id, topic = pe.va_uint32(pushes[0]+index*8), pe.va_uint32(pushes[0]+index*8+4)
            lines.append(f'    0x{control_id:x}, 0x{topic:x},')
            if not control_id and not topic: break
        else: raise SurveyError('unterminated time help')
        lines += ['};', f'#define WORLD_TIME_{name.upper()}_VTABLE_RVA 0x{vtable-pe.uiBase:x}',
                  f'#define WORLD_TIME_{name.upper()}_BASE_CTOR 0x{ctor[0][1]:x}', f'#define WORLD_TIME_{name.upper()}_BASE_DTOR 0x{dtor[0][1]:x}']
        all_ctors.update(slot for _, slot in ctor[1:]); all_dtors.update(slot for _, slot in dtor)
    lines += ['static const struct world_time_class s_time_classes[] = {']
    for name, _, _, _, _, _, _, vtable, slots, count, template, size, message_map, _ in classes:
        lines.append(f'    {{s_time_{name}_controls, s_time_{name}_cleanup, s_time_{name}_ddx, s_time_{name}_help, {count}, 0x{template:x}, 0x{size:x}, WORLD_TIME_{name.upper()}_BASE_CTOR, WORLD_TIME_{name.upper()}_BASE_DTOR}},')
    lines += ['};']
    Path('src/world/world_time_tables.inc').write_text('\n'.join(lines)+'\n')
    hooks = ['/* Generated by tools/gen_world_time.py; imported class ABI. */']
    hooks += ['WORLD_TIME_BASE_HOOK(25804)', 'WORLD_TIME_BASE_HOOK(2574c)']
    hooks += [f'WORLD_CTOR_HOOK({slot:x})' for slot in sorted(all_ctors)]
    hooks += [f'WORLD_DTOR_HOOK({slot:x})' for slot in sorted(all_dtors)]
    Path('src/world/world_time_hooks.inc').write_text('\n'.join(hooks)+'\n')


if __name__ == '__main__':
    main()
