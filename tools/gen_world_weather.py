#!/usr/bin/env python3
"""Extract basic-weather class metadata; no code or resource payloads."""
from pathlib import Path
import re
from dialogmap import Fs98Pe, SurveyError
from gen_world_tables import instructions, object_calls, cleanup_imports


def main():
    pe = Fs98Pe('orig/English/World.DLL')
    if pe.uiBase != 0x223f0000 or pe.linkage()['id'] != 0x80000006:
        raise SurveyError('expected reference World')
    ctor_asm = instructions(0x2d40, 0x2e50)
    dtor_asm = instructions(0x2e70, 0x2f80)
    ctor, dtor = object_calls(ctor_asm), list(reversed(object_calls(dtor_asm)))
    if len(ctor) != 14 or [offset for offset, _ in ctor] != [offset for offset, _ in dtor]:
        raise SurveyError('weather control graph moved')
    unwind = cleanup_imports(pe, ctor_asm, 13)
    if unwind != cleanup_imports(pe, dtor_asm, 13) or unwind != dict(dtor[:-1]):
        raise SurveyError('weather cleanup graph moved')
    lines = ['/* Generated by tools/gen_world_weather.py; ABI metadata only. */',
             'static const struct fs98_world_control s_weather_controls[] = {']
    lines += [f'    {{0x{offset:x}, 0x{construct:x}, 0x{destroy:x}}},'
              for (offset, construct), (_, destroy) in zip(ctor[1:], dtor[1:])]
    lines += ['};', 'static const uint32_t s_weather_cleanup[] = {']
    lines += [f'    0x{unwind.get(offset, destroy):x},' for offset, destroy in dtor[1:]]
    lines += ['};', 'static const uint16_t s_weather_ddx[][2] = {']
    bindings = []
    offset = control_id = None
    for op in instructions(0x2f80, 0x3070):
        match = re.search(r'(?:lea\s+\w+,\[esi\+0x|add\s+esi,0x)([0-9a-f]+)', op)
        if match:
            offset = int(match[1], 16)
        match = re.fullmatch(r'push\s+0x([0-9a-f]+)', op)
        if match:
            control_id = int(match[1], 16)
        if op == 'call   0x224099c4':
            if offset is None or control_id is None:
                raise SurveyError('unknown weather DDX')
            bindings.append((offset, control_id))
            offset = control_id = None
    if sorted(offset for offset, _ in bindings) != sorted(offset for offset, _ in ctor[2:]):
        raise SurveyError('weather DDX differs from controls')
    lines += [f'    {{0x{offset:x}, 0x{control_id:x}}},' for offset, control_id in bindings]
    lines += ['};', 'static const uint32_t s_weather_help[] = {']
    pushes = [int(match[1], 16) for op in instructions(0x3400, 0x3420)
              if (match := re.fullmatch(r'push\s+0x([0-9a-f]+)', op))]
    if len(pushes) != 3 or pushes[1] != 12:
        raise SurveyError('weather help changed')
    for index in range(64):
        control_id, topic = pe.va_uint32(pushes[0] + index * 8), pe.va_uint32(pushes[0] + index * 8 + 4)
        lines.append(f'    0x{control_id:x}, 0x{topic:x},')
        if not control_id and not topic:
            break
    else:
        raise SurveyError('unterminated weather help map')
    vtables = [int(match[1], 16) for op in ctor_asm
               if (match := re.fullmatch(r'mov\s+DWORD PTR \[esi\],0x([0-9a-f]+)', op))]
    if vtables != [0x2240e390] or pe.va_uint32(vtables[0] + 4) != 0x223f2e50:
        raise SurveyError('weather vtable changed')
    lines += ['};', '#define WORLD_WEATHER_VTABLE_RVA 0x1e390',
              f'#define WORLD_WEATHER_BASE_CTOR 0x{ctor[0][1]:x}',
              f'#define WORLD_WEATHER_BASE_DTOR 0x{dtor[0][1]:x}']
    if pe.va_uint32(0x2240e310) != 0x223f5d40:
        raise SurveyError('basic-weather base message map moved')
    lines += ['static const uint32_t s_weather_vtable_rvas[] = {']
    lines += [f'    0x{pe.va_uint32(0x2240e390 + index * 4) - pe.uiBase:x},' for index in range(60)]
    lines += ['};', 'static const uint32_t s_weather_messages[][6] = {']
    for index in range(5):
        fields = [pe.va_uint32(0x2240e318 + index * 24 + field * 4) for field in range(6)]
        lines.append('    {' + ', '.join(f'0x{value:x}' for value in fields) + '},')
        if not any(fields): break
    else: raise SurveyError('basic-weather message map not terminated')
    if index != 4: raise SurveyError('basic-weather message count changed')
    lines += ['};']
    Path('src/world/world_weather_tables.inc').write_text('\n'.join(lines) + '\n')
    hooks = ['/* Generated by tools/gen_world_weather.py; import ABI metadata. */']
    for macro, slots in [('WORLD_BASE_HOOK', [ctor[0][1]]),
                         ('WORLD_CTOR_HOOK', sorted({slot for _, slot in ctor[1:]})),
                         ('WORLD_DTOR_HOOK', sorted({slot for _, slot in dtor}))]:
        hooks += [f'{macro}({slot:x})' for slot in slots]
    Path('src/world/world_weather_hooks.inc').write_text('\n'.join(hooks) + '\n')


if __name__ == '__main__':
    main()
